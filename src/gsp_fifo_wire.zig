//! Pinned 570.144 raw C56F allocation and inherited channel controls.
//! Explicit context shares are children of the same TSG as the channel.
const std = @import("std");
const context = @import("gsp_context_wire.zig");
const exchange = @import("gsp_exchange.zig");
const nv = @import("r4nv_binding");
pub const Error = context.Error;
pub const Operation = enum { classes, allocate, bind, token, promote_graphics, allocate_copy, allocate_graphics, allocate_compute, allocate_gr_copy, enable, disable, free_gr_copy, free_compute, free_copy, free };
pub const Engine = enum { none, copy, graphics };
pub const max_bytes: usize = 584;
pub const entries: u32 = 512;
pub const Config = struct {
    chip_id: u16 = 0x176,
    context: context.Binding,
    handle: u32,
    rm_engine: u32,
    runqueue: u8,
    address: u64,
    instance: u64,
    userd: u64,
    system_userd: bool = false,
    engine: Engine = .none,
    object_handle: u32 = 0,
    object_class: u32 = 0,
    engine_mask: u32 = nv.native_engine_graphics,
    compute_handle: u32 = 0,
    compute_class: u32 = 0,
    copy_handle: u32 = 0,
    copy_class: u32 = 0,
    copy_rm_engine: u32 = 0,
    graphics: ?context.graphics.Promotion = null,
    methods: u64,
    method_bytes: u32,
};
pub const Reply = union(enum) { rejected: u32, ok: u32 };
pub fn function(op: Operation) u32 { return switch (op) { .allocate, .allocate_copy, .allocate_graphics, .allocate_compute, .allocate_gr_copy => 103, .free, .free_copy, .free_compute, .free_gr_copy => 10, else => 76 }; }
pub fn command(op: Operation) u32 { return switch (op) { .bind => 0xa06f0104, .token => 0xc36f0108, .promote_graphics => 0x2080012b, .enable, .disable => 0xa06f0103, else => 0 }; }
pub fn length(op: Operation) usize { return switch (op) { .classes => 428, .allocate => 400, .allocate_copy, .allocate_gr_copy => 40, .allocate_graphics => 48, .allocate_compute => 32, .promote_graphics => 584, .free, .free_copy, .free_compute, .free_gr_copy => 16, .enable, .disable => 26, else => 28 }; }
pub fn validGraphicsEngines(mask: u32) bool {
    return mask & nv.native_engine_graphics != 0 and mask & ~(nv.native_engine_graphics | nv.native_engine_compute | nv.native_engine_copy) == 0;
}
pub const Classes = struct { primary: u32, compute: u32, copy: u32 };
/// Only consume the class payload after context.decode has validated its bounds.
pub fn selectedClasses(config: Config, payload: []const u8) Classes {
    const profile = @import("generation.zig").get(config.chip_id).?;
    const copy = if (context.supports(payload, profile.copy[0])) profile.copy[0]
        else if (profile.copy[1] != 0 and context.supports(payload, profile.copy[1])) profile.copy[1] else 0;
    return .{
        .primary = switch (config.engine) {
            .none => 0, .copy => copy,
            .graphics => if (context.supports(payload, profile.render)) profile.render else 0,
        },
        .compute = if (config.compute_handle != 0 and context.supports(payload, profile.computeClass())) profile.computeClass() else 0,
        .copy = if (config.copy_handle != 0) copy else 0,
    };
}
pub const word = context.word;
fn put(out: []u8, at: usize, value: u32) void { std.mem.writeInt(u32, out[at..][0..4], value, .little); }
fn wide(out: []u8, at: usize, value: u64) void { std.mem.writeInt(u64, out[at..][0..8], value, .little); }
pub fn validate(config: Config) Error!void {
    const profile = @import("generation.zig").get(config.chip_id) orelse return error.Unsupported;
    try context.validate(config.context); _ = try context.nvEngine(config.rm_engine);
    if (config.graphics) |graphics| {
        if (config.engine != .graphics) return error.Unsupported;
        if (graphics.golden and config.engine_mask != nv.native_engine_graphics) return error.Unsupported;
        graphics.validate() catch return error.Bounds;
    }
    if (config.engine == .graphics) {
        if (!validGraphicsEngines(config.engine_mask) or
            (config.engine_mask & nv.native_engine_compute != 0) != (config.compute_handle != 0) or
            (config.engine_mask & nv.native_engine_copy != 0) != (config.copy_handle != 0)) return error.Unsupported;
        if (config.compute_handle != 0 and (profile.computeClass() == 0 or
            (config.compute_class != 0 and config.compute_class != profile.computeClass()))) return error.Unsupported;
        if (config.copy_handle != 0 and (config.copy_rm_engine < 9 or config.copy_rm_engine > 28 or
            (config.copy_class != 0 and config.copy_class != profile.copy[0] and config.copy_class != profile.copy[1]))) return error.Unsupported;
    } else if (config.engine_mask != nv.native_engine_graphics or config.compute_handle != 0 or config.copy_handle != 0) return error.Unsupported;
    if ((config.compute_handle == 0 and config.compute_class != 0) or
        (config.copy_handle == 0 and (config.copy_class != 0 or config.copy_rm_engine != 0))) return error.Handle;
    const objects = [_]u32{config.object_handle, config.compute_handle, config.copy_handle};
    for (objects, 0..) |object, index| {
        if (object == 0) continue;
        for (objects[0..index]) |prior| if (object == prior) return error.Handle;
        for ([_]u32{config.handle, config.context.client, config.context.device, config.context.subdevice, config.context.vaspace, config.context.group, config.context.share}) |handle|
            if (object == handle) return error.Handle;
    }
    for ([_]u32{0,config.context.client,config.context.device,config.context.subdevice,config.context.vaspace,config.context.group,config.context.share}) |handle|
        if (config.handle == handle) return error.Handle;
    if (config.runqueue >= 2 or config.address == 0 or config.address & 4095 != 0 or config.address > (@as(u64, 1) << 40) - 12288 or
        config.instance == 0 or config.instance & 4095 != 0 or config.userd == 0 or config.userd & 4095 != 0 or
        config.methods == 0 or config.methods & 4095 != 0 or config.method_bytes == 0) return error.Bounds;
    const starts = [_]u64{config.instance,config.userd,config.methods};
    const sizes = [_]u64{4096,512,config.method_bytes};
    for (starts, sizes, 0..) |start, size, i| {
        const end = std.math.add(u64, start, size) catch return error.Bounds;
        for (starts[0..i], sizes[0..i], 0..) |prior, bytes, j| {
            if (config.system_userd and (i == 1 or j == 1)) continue;
            if (start < prior + bytes and prior < end) return error.Bounds;
        }
    }
    if (config.system_userd) {
        if (config.userd > (@as(u64, 1) << 40) - 4096 or config.object_handle == 0) return error.Bounds;
        switch (config.engine) {
            .none => return error.Unsupported,
            .copy => if (config.rm_engine < 9 or (config.object_class != 0 and config.object_class != profile.copy[0] and config.object_class != profile.copy[1])) return error.Unsupported,
            .graphics => if (config.rm_engine != 1 or (config.object_class != 0 and config.object_class != profile.render)) return error.Unsupported,
        }
        for ([_]u32{config.handle, config.context.client,config.context.device,config.context.subdevice,config.context.vaspace,config.context.group,config.context.share}) |handle|
            if (config.object_handle == handle) return error.Handle;
    } else if (config.object_handle != 0 or config.object_class != 0 or config.engine != .none) return error.Handle;
}
fn descriptor(out: []u8, at: usize, base: u64, bytes: u64, cache: u32) void {
    wide(out, at, base); wide(out, at + 8, bytes); put(out, at + 16, 2); put(out, at + 20, cache);
}
pub fn encode(config: Config, op: Operation, output: []u8) Error![]const u8 {
    try validate(config);
    if (output.len < length(op)) return error.Bounds;
    const out = output[0..length(op)]; @memset(out, 0); put(out, 0, config.context.client);
    switch (op) {
        .classes => return context.encode(config.context, config.rm_engine, 0, .classes, output),
        .allocate => {
            put(out, 4, config.context.group); put(out, 8, config.handle); put(out, 12, 0xc56f); put(out, 20, 368);
            wide(out, 40, config.address); put(out, 48, entries);
            // New USERD page at index zero, chosen by RM. Delay scheduling;
            // deny physical CE addressing. No caller-selected hardware CHID.
            const golden = if (config.graphics) |graphics| graphics.golden else false;
            put(out, 52, 0x8c0 | (@as(u32, config.runqueue) << 4) | (if (golden) @as(u32, 0x20) else 0));
            put(out, 56, config.context.share); put(out, 160, try context.nvEngine(config.rm_engine));
            descriptor(out, 176, config.instance, 4096, 1);
            descriptor(out, 200, config.userd, 512, 1);
            if (config.system_userd) { put(out, 216, 1); put(out, 220, 0); } // ADDR_SYSMEM, NV_MEMORY_CACHED.
            descriptor(out, 224, config.instance, 512, 1);
            descriptor(out, 248, config.methods, config.method_bytes, 0);
            put(out, 276, if (golden) 0x15 else 0x14); // Golden ADMIN; normal USER. Error/ECC notifiers NONE.
        },
        .promote_graphics => {
            const graphics = config.graphics orelse return error.Unsupported;
            put(out, 4, config.context.subdevice); put(out, 8, command(op)); put(out, 16, 560);
            put(out, 24, 1); put(out, 36, config.context.client); put(out, 40, config.handle); put(out, 64, graphics.count);
            for (graphics.entries[0..graphics.count], 0..) |entry, index| {
                const at = 72 + index * 32;
                wide(out, at, entry.physical); wide(out, at + 8, entry.address); wide(out, at + 16, entry.bytes);
                put(out, at + 24, if (entry.initialize) 4 else 0);
                std.mem.writeInt(u16, out[at + 28..][0..2], entry.id, .little);
                out[at + 30] = @intFromBool(entry.initialize); out[at + 31] = @intFromBool(entry.nonmapped);
            }
        },
        .allocate_copy, .allocate_gr_copy => {
            const auxiliary = op == .allocate_gr_copy;
            if (!config.system_userd or (if (auxiliary) config.engine != .graphics or config.copy_handle == 0 or config.copy_class == 0
                else config.engine != .copy or config.object_class == 0)) return error.Unsupported;
            put(out, 4, config.handle); put(out, 8, if (auxiliary) config.copy_handle else config.object_handle);
            put(out, 12, if (auxiliary) config.copy_class else config.object_class); put(out, 20, 8);
            put(out, 32, 1); put(out, 36, try context.nvEngine(if (auxiliary) config.copy_rm_engine else config.rm_engine));
        },
        .allocate_graphics => {
            if (!config.system_userd or config.engine != .graphics or config.object_class == 0) return error.Unsupported;
            put(out, 4, config.handle); put(out, 8, config.object_handle); put(out, 12, config.object_class); put(out, 20, 16);
            // nvos.h NV_GR_ALLOCATION_PARAMETERS: version, flags, size, caps.
            // Caps is RM output; it never changes the admitted class/profile.
            put(out, 32, 2); put(out, 40, 16);
        },
        .allocate_compute => {
            if (!config.system_userd or config.engine != .graphics or config.compute_handle == 0 or config.compute_class == 0) return error.Unsupported;
            // Nouveau's generic RM GR-object allocator passes no parameters.
            put(out, 4, config.handle); put(out, 8, config.compute_handle); put(out, 12, config.compute_class);
        },
        .free, .free_copy, .free_compute, .free_gr_copy => {
            const handle = switch (op) { .free => config.handle, .free_copy => config.object_handle, .free_compute => config.compute_handle, .free_gr_copy => config.copy_handle, else => unreachable };
            if (handle == 0) return error.Handle;
            put(out, 8, handle);
        },
        else => {
            put(out, 4, config.handle); put(out, 8, command(op)); put(out, 16, @intCast(out.len - 24));
            if (op == .bind) put(out, 24, try context.nvEngine(config.rm_engine));
            if (op == .enable) out[24] = 1; // bSkipSubmit remains false.
        },
    }
    return out;
}
pub fn decode(config: Config, op: Operation, request: []const u8, record: exchange.message.Record) Error!Reply {
    try validate(config);
    if (op == .classes) {
        const reply = try context.decode(config.context, config.rm_engine, 0, .classes, request, record);
        if (reply == .rejected) return .{ .rejected = reply.rejected };
        const classes = selectedClasses(config, reply.ok);
        return .{ .ok = if ((config.compute_handle != 0 and classes.compute == 0) or
            (config.copy_handle != 0 and classes.copy == 0)) 0 else classes.primary };
    }
    if (request.len != length(op) or record.rpc.function != function(op) or record.rpc.cpu_rm_gfid != 0) return error.Payload;
    if (record.rpc.result != 0) return error.FirmwareResult;
    const header: usize = if (function(op) == 103) 32 else if (function(op) == 10) 16 else 24;
    const status_at: usize = if (function(op) == 103) 16 else 12;
    const data = record.payload;
    if (data.len != header and data.len != request.len) return error.Payload;
    for (data[0..header], 0..) |value, i| {
        if (i >= status_at and i < status_at + 4) continue;
        if (value != request[i]) return error.Unexpected;
    }
    const status = word(data, status_at);
    if (status != 0) return .{ .rejected = status };
    if (data.len != request.len) return error.Payload;
    for (data[header..], header..) |value, i| {
        if ((op == .allocate and i >= 164 and i < 168) or op == .token or (op == .allocate_graphics and i >= 44 and i < 48)) continue;
        if (value != request[i]) return error.Payload;
    }
    const result = if (op == .allocate) word(data, 164) else if (op == .token) word(data, 24) else if (op == .allocate_graphics) word(data, 44) else 0;
    // cid is the RM session identifier, NOT the hardware channel index.
    if (op == .allocate and result == 0) return error.Payload;
    return .{ .ok = result };
}
