//! Independent NV50 virtual allocations and exact NVOS46 mapping receipts.
//! The pinned v03_00 unmap RPC has no length field: unmap always refers to
//! one complete prior mapping. Splitting or replacing it belongs to its owner.
const std = @import("std");
const exchange = @import("gsp_exchange.zig");
const vaspace = @import("gsp_vaspace.zig");
pub const Error = exchange.Error;
pub const Encoded = struct { function: u32, bytes: []const u8 };
pub const Reply = union(enum) { ok: u64, rejected: u32 };
pub const Location = enum { system, video };
// Uncompressed TU102+ kinds, from NVIDIA570.144 dev_mmu.h and
// memmgrChooseKindZ_TU102. Depth/stencil attributes are required as well as
// format: RM may choose the kind again from type/attributes during allocation.
const Layout = struct { kind: u32, memory_type: u32, attributes: u32 };
fn layout(blocklinear: bool, pte_kind: u8) Error!Layout {
    const kind: u32 = if (pte_kind != 0) pte_kind else if (blocklinear) 6 else 0;
    const tile: u32 = 2 << 16;
    return switch (kind) {
        0 => .{ .kind = 0, .memory_type = 6, .attributes = 0 },
        1 => .{ .kind = 1, .memory_type = 1, .attributes = tile | 2 | (7 << 19) },
        2 => .{ .kind = 2, .memory_type = 16, .attributes = tile | 1 },
        3 => .{ .kind = 3, .memory_type = 1, .attributes = tile | 4 | (1 << 19) },
        4 => .{ .kind = 4, .memory_type = 1, .attributes = tile | 5 | (1 << 18) | (5 << 19) },
        5 => .{ .kind = 5, .memory_type = 1, .attributes = tile | 4 },
        6 => .{ .kind = 6, .memory_type = 6, .attributes = tile },
        else => error.Profile, // Compression and unknown kinds are not implemented.
    };
}
const system_attributes: u32 = 0x22800000;
const system_gpu_cache: u32 = 8;
const system_snoop: u32 = 0x10;
/// CPU cache visibility only. The RM mapping must still be acknowledged and
/// Vulkan/engine barriers must order actual CPU/GPU accesses. Pinned nvos.h:
/// NVOS32_ATTR_COHERENCY_CACHED, ATTR2_GPU_CACHEABLE_NO, NVOS46_CACHE_SNOOP_ENABLE.
pub fn hostCoherentSystemPolicy() bool {
    return @import("builtin").cpu.arch == .x86_64 and
        system_attributes & 0xe0000000 == 0x20000000 and
        system_gpu_cache & 0xc == 8 and system_snoop & 0x10 != 0;
}
pub const Allocation = struct {
    space: vaspace.Info,
    object: u32,
    bytes: u64,
    alignment: u64 = 4096,
    fixed_address: u64 = 0,
    location: Location = .system,
    blocklinear: bool = false,
    pte_kind: u8 = 0,
    privileged: bool = false,

    pub fn validate(self: Allocation) Error!void {
        _ = try layout(self.blocklinear, self.pte_kind);
        const s = self.space;
        if (s.epoch == 0 or s.client == 0 or s.device == 0 or s.handle == 0 or self.object == 0) return error.Handle;
        if (s.client == s.device or s.client == s.handle or s.device == s.handle) return error.Handle;
        for ([_]u32{ s.client, s.device, s.handle }) |name| if (self.object == name) return error.Handle;
        if (s.base == 0 or (s.base | s.bytes) & 4095 != 0 or s.bytes < 4096 or
            s.base >= @as(u64, 1) << 49 or s.bytes > (@as(u64, 1) << 49) - s.base or
            self.bytes == 0 or self.bytes & 4095 != 0 or self.bytes > s.bytes or
            self.alignment < 4096 or self.alignment > s.bytes or !std.math.isPowerOfTwo(self.alignment)) return error.Bounds;
        if (self.fixed_address != 0) try self.validateAddress(self.fixed_address);
    }
    pub fn validateAddress(self: Allocation, address: u64) Error!void {
        const s = self.space;
        if (self.alignment == 0 or self.bytes > s.bytes or address < s.base or
            address % self.alignment != 0 or address - s.base > s.bytes - self.bytes or
            (self.fixed_address != 0 and address != self.fixed_address)) return error.Bounds;
    }
};
pub const Mapping = struct {
    allocation: Allocation,
    address: u64,
    memory: u32,
    memory_bytes: u64,
    memory_offset: u64 = 0,
    virtual_offset: u64 = 0,
    bytes: u64,
    location: Location,
    readonly: bool = false,
    virtual_kind: bool = false,

    pub fn validate(self: Mapping) Error!void {
        try self.allocation.validate();
        try self.allocation.validateAddress(self.address);
        if ((self.allocation.blocklinear or self.allocation.pte_kind != 0) and !self.virtual_kind) return error.Profile;
        const s = self.allocation.space;
        if (self.memory == 0) return error.Handle;
        for ([_]u32{ s.client, s.device, s.handle, self.allocation.object }) |name| if (self.memory == name) return error.Handle;
        if (self.bytes == 0 or (self.memory_bytes | self.memory_offset | self.virtual_offset | self.bytes) & 4095 != 0 or
            self.bytes > self.memory_bytes or self.memory_offset > self.memory_bytes - self.bytes or
            self.bytes > self.allocation.bytes or self.virtual_offset > self.allocation.bytes - self.bytes) return error.Bounds;
    }
};
pub const MapOperation = enum { map, unmap };
fn put(out: []u8, at: usize, value: u32) void { std.mem.writeInt(u32, out[at..][0..4], value, .little); }
fn wide(out: []u8, at: usize, value: u64) void { std.mem.writeInt(u64, out[at..][0..8], value, .little); }
fn word(in: []const u8, at: usize) u32 { return std.mem.readInt(u32, in[at..][0..4], .little); }
fn long(in: []const u8, at: usize) u64 { return std.mem.readInt(u64, in[at..][0..8], .little); }

pub fn allocate(value: Allocation, output: []u8) Error!Encoded {
    try value.validate();
    if (output.len < 160) return error.Bounds;
    const out = output[0..160];
    @memset(out, 0);
    put(out, 0, value.space.client);
    put(out, 4, value.space.device);
    put(out, 8, value.object);
    put(out, 12, 0x50a0); // NV50_MEMORY_VIRTUAL; RM owns page tables.
    put(out, 20, 128);
    const p = out[32..];
    const image = try layout(value.blocklinear, value.pte_kind);
    put(p, 4, image.memory_type);
    put(p, 8, 0x80100 | @as(u32, if (value.fixed_address != 0) 0x10 else 0) |
        @as(u32, if (value.privileged) 0x08000000 else 0));
    put(p, 24, @as(u32, if (value.location == .system) system_attributes else 0x00800000) |
        image.attributes);
    put(p, 28, if (value.location == .system) system_gpu_cache else 4); // Explicit GPU cache policy.
    put(p, 32, image.kind);
    wide(p, 64, value.bytes);
    wide(p, 72, value.alignment);
    wide(p, 80, value.fixed_address);
    put(p, 108, value.space.handle);
    return .{ .function = 103, .bytes = out };
}
pub fn free(value: Allocation, output: []u8) Error!Encoded {
    try value.validate();
    if (output.len < 16) return error.Bounds;
    const out = output[0..16];
    @memset(out, 0);
    put(out, 0, value.space.client);
    put(out, 8, value.object);
    return .{ .function = 10, .bytes = out };
}
pub fn mapping(value: Mapping, operation: MapOperation, output: []u8) Error!Encoded {
    try value.validate();
    const size: usize = if (operation == .map) 56 else 40;
    if (output.len < size) return error.Bounds;
    const out = output[0..size];
    @memset(out, 0);
    put(out, 0, value.allocation.space.client);
    put(out, 4, value.allocation.space.device);
    put(out, 8, value.allocation.object);
    put(out, 12, value.memory);
    if (operation == .map) {
        wide(out, 16, value.memory_offset);
        wide(out, 24, value.bytes);
        put(out, 32, 0x100 | @as(u32, if (value.location == .system) system_snoop else 0) |
            @as(u32, @intFromBool(value.readonly)) | @as(u32, if (value.virtual_kind) 8 else 0));
        wide(out, 40, value.virtual_offset); // Relative non-CTXDMA input, absolute output.
    } else wide(out, 24, value.address + value.virtual_offset);
    return .{ .function = if (operation == .map) 14 else 15, .bytes = out };
}
fn receipt(record: exchange.message.Record, request: Encoded, status_at: usize, short_allocate: bool) Error!u32 {
    if (record.rpc.function != request.function or record.rpc.cpu_rm_gfid != 0) return error.Unexpected;
    if (record.rpc.result == exchange.message.pending) return error.Payload;
    // RPC failures are not ownership receipts. Only the inner RM status can
    // prove rejection without creating an object or a translation.
    if (record.rpc.result != 0) return error.FirmwareResult;
    const data = record.payload;
    if (data.len != request.bytes.len and !(short_allocate and data.len == 32)) return error.Payload;
    for (data[0..@min(data.len, 32)], 0..) |value, i| {
        if (i >= status_at and i < status_at + 4) continue;
        if (value != request.bytes[i]) return error.Unexpected;
    }
    return word(data, status_at);
}
pub fn allocated(value: Allocation, record: exchange.message.Record) Error!Reply {
    var request: [160]u8 = undefined;
    const status = try receipt(record, try allocate(value, &request), 16, true);
    if (status != 0) return .{ .rejected = status };
    if (record.payload.len != 160) return error.Payload;
    const p = record.payload[32..];
    for (p, 0..) |v, i| {
        if (i >= 80 and i < 96) continue; // Returned offset and limit only.
        if (v != request[32 + i]) return error.Payload;
    }
    if (long(p, 88) != value.bytes - 1) return error.Bounds;
    const address = long(p, 80);
    try value.validateAddress(address);
    return .{ .ok = address };
}
pub fn freed(value: Allocation, record: exchange.message.Record) Error!Reply {
    var request: [16]u8 = undefined;
    const status = try receipt(record, try free(value, &request), 12, false);
    return if (status == 0) .{ .ok = 0 } else .{ .rejected = status };
}
pub fn mapped(value: Mapping, operation: MapOperation, record: exchange.message.Record) Error!Reply {
    var request: [56]u8 = undefined;
    const encoded = try mapping(value, operation, &request);
    const status_at: usize = if (operation == .map) 48 else 32;
    const status = try receipt(record, encoded, status_at, false);
    if (status != 0) return .{ .rejected = status };
    for (record.payload, 0..) |v, i| {
        if (i >= status_at and i < status_at + 4) continue;
        if (operation == .map and i >= 40 and i < 48) continue;
        if (v != request[i]) return error.Payload;
    }
    const address = value.address + value.virtual_offset;
    if (operation == .map and long(record.payload, 40) != address) return error.Bounds;
    return .{ .ok = address };
}
