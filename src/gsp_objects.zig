//! Pinned GA106 RM object hierarchy and explicit lifetime over the shared RPC
//! owner. This manages RM names, not GPU memory or hardware initialization.
//! The caller reserves all names for this epoch; success is a validated RM
//! reply plus queue ACK, never a locally invented live firmware object.
const std = @import("std");
const exchange = @import("gsp_exchange.zig");
const boot = @import("gsp_boot_events.zig");
const display = @import("gsp_display_rpc.zig");
const message = exchange.message;
pub const Error = exchange.Error;
pub const Kind = enum(u2) { client, device, subdevice, display };
pub const Operation = union(enum) { allocate: Kind, free: Kind };
pub const Handles = struct { client: u32, device: u32, subdevice: u32, display: u32 };
pub const max_request_bytes = 152;
pub const Response = union(enum) { ok: void, rm_error: u32, rpc_error: u32 };
pub const Encoded = struct { function: u32, bytes: []const u8 };
pub const Plan = struct {
    epoch: u64,
    handles: Handles,
    process_id: u32,
    process_name: [100]u8,

    /// Names must already be reserved in the caller's RM namespace. Validate
    /// local uniqueness, never allocate a global name from PCI/BDF/DCB indices.
    pub fn init(epoch: u64, handles: Handles, process_id: u32, name: []const u8) Error!Plan {
        if (epoch == 0) return error.Handle;
        const all = [_]u32{ handles.client, handles.device, handles.subdevice, handles.display };
        for (all, 0..) |value, i| {
            if (value == 0) return error.Handle;
            for (all[0..i]) |previous| if (previous == value) return error.Handle;
        }
        if (name.len >= 100 or std.mem.indexOfScalar(u8, name, 0) != null) return error.Payload;
        var result = Plan{ .epoch = epoch, .handles = handles, .process_id = process_id, .process_name = @splat(0) };
        @memcpy(result.process_name[0..name.len], name);
        return result;
    }
    pub fn validate(self: *const Plan) Error!void {
        const end = std.mem.indexOfScalar(u8, &self.process_name, 0) orelse return error.Payload;
        _ = try init(self.epoch, self.handles, self.process_id, self.process_name[0..end]);
        for (self.process_name[end..]) |byte| if (byte != 0) return error.Payload;
    }
    pub fn handle(self: *const Plan, kind: Kind) u32 {
        return switch (kind) {
            .client => self.handles.client,
            .device => self.handles.device,
            .subdevice => self.handles.subdevice,
            .display => self.handles.display,
        };
    }
    pub fn parent(self: *const Plan, kind: Kind) u32 {
        // Root's supplied handle is also its parent in the referenced GSP
        // client constructor. Subdevice and display are siblings under device.
        return switch (kind) {
            .client, .device => self.handles.client,
            .subdevice, .display => self.handles.device,
        };
    }
};
fn word(bytes: []const u8, offset: usize) u32 {
    return std.mem.readInt(u32, bytes[offset..][0..4], .little);
}
fn put(bytes: []u8, offset: usize, value: u32) void {
    std.mem.writeInt(u32, bytes[offset..][0..4], value, .little);
}
pub fn class(kind: Kind) u32 {
    return switch (kind) {
        .client => 0,
        .device => 0x80,
        .subdevice => 0x2080,
        .display => 0x73,
    };
}
pub fn paramsSize(kind: Kind) usize {
    // These are the original 570.144 x86_64 C sizes. The older Nouveau535
    // client excerpt has108 bytes; do not omit570's padding/pOsPidInfo field.
    return switch (kind) {
        .client => 120,
        .device => 56,
        .subdevice => 4,
        .display => 0,
    };
}
pub fn encode(plan: *const Plan, operation: Operation, output: []u8) Error!Encoded {
    try plan.validate();
    const size: usize = switch (operation) {
        .allocate => |kind| 32 + paramsSize(kind),
        .free => 16,
    };
    if (output.len < size) return error.Bounds;
    const bytes = output[0..size];
    @memset(bytes, 0);
    put(bytes, 0, plan.handles.client);
    switch (operation) {
        .allocate => |kind| {
            put(bytes, 4, plan.parent(kind));
            put(bytes, 8, plan.handle(kind));
            put(bytes, 12, class(kind));
            put(bytes, 20, @intCast(paramsSize(kind)));
            const params = bytes[32..];
            switch (kind) {
                .client => {
                    put(params, 0, plan.handles.client);
                    put(params, 4, plan.process_id);
                    @memcpy(params[8..108], &plan.process_name);
                    // Padding108..112 and pOsPidInfo112..120 remain zero:
                    // no host pointer crosses the firmware wire.
                },
                .device => {
                    // Standalone GSP device/subdevice index0, no target client,
                    // VA policy override or address-space allocation request.
                    put(params, 4, plan.handles.client);
                },
                .subdevice, .display => {},
            }
            return .{ .function = 103, .bytes = bytes };
        },
        .free => |kind| {
            // NVOS00: hObjectParent is the documented null handle here.
            put(bytes, 8, plan.handle(kind));
            return .{ .function = 10, .bytes = bytes };
        },
    }
}
pub fn decode(plan: *const Plan, operation: Operation, record: message.Record) Error!Response {
    const expected: u32 = if (operation == .allocate) 103 else 10;
    if (record.rpc.function != expected) return error.Unexpected;
    if (record.rpc.cpu_rm_gfid != 0) return error.Guest;
    if (record.rpc.result == message.pending) return error.Payload;
    if (record.rpc.result != 0) return .{ .rpc_error = record.rpc.result };
    const bytes = record.payload;
    switch (operation) {
        .allocate => |kind| {
            // Alloc consumers need the fixed32-byte result. Accept that header
            // or its complete original parameter echo; never a partial tail,
            // serialized flags, different identity or copied output pointer.
            if (bytes.len != 32 and bytes.len != 32 + paramsSize(kind)) return error.Payload;
            if (word(bytes, 0) != plan.handles.client or word(bytes, 4) != plan.parent(kind) or
                word(bytes, 8) != plan.handle(kind) or word(bytes, 12) != class(kind)) return error.Unexpected;
            if (word(bytes, 20) != paramsSize(kind) or word(bytes, 24) != 0 or word(bytes, 28) != 0) return error.Payload;
            const status = word(bytes, 16);
            return if (status == 0) .ok else .{ .rm_error = status };
        },
        .free => |kind| {
            if (bytes.len != 16) return error.Payload;
            if (word(bytes, 0) != plan.handles.client or word(bytes, 4) != 0 or word(bytes, 8) != plan.handle(kind)) return error.Unexpected;
            const status = word(bytes, 12);
            return if (status == 0) .ok else .{ .rm_error = status };
        },
    }
}

pub const Slot = enum { absent, creating, live, freeing, uncertain };
pub const State = enum { creating, objects_ready, loaned, rejected, destroying, objects_closed, finished, failed };
pub const Status = struct { operation: Operation, result: Response };
pub const Loan = struct { runtime: boot.Handoff, object: display.Object };
pub const Owner = struct {
    exchange: exchange.Exchange,
    plan: Plan,
    deadline: u64,
    state: State = .creating,
    slots: [4]Slot = @splat(.absent),
    outstanding: ?Operation = null,
    request_bytes: [max_request_bytes]u8 = undefined,
    last_status: ?Status = null,

    /// Keep the owner stable once polling begins: the exchange borrows its
    /// request buffer. INIT_DONE, actual session backing and globally reserved
    /// handles belong to the preceding runtime owner, not this constructor.
    pub fn init(runtime: *boot.Handoff, plan: Plan, deadline: u64) Error!Owner {
        try plan.validate();
        if (plan.epoch != runtime.session.epoch) return error.Handle;
        return .{ .exchange = try exchange.Exchange.init(runtime, deadline), .plan = plan, .deadline = deadline };
    }
    fn fail(self: *Owner, reason: Error) Error {
        if (self.state == .loaned or self.state == .finished) return error.State;
        if (self.outstanding) |operation| {
            const kind = switch (operation) {
                .allocate, .free => |value| value,
            };
            self.slots[@intFromEnum(kind)] = .uncertain;
        }
        self.state = .failed;
        return self.exchange.fail(reason);
    }
    /// At most one receive/send attempt. Only this owner validates and ACKs
    /// object results; returned notifications still require the actual handler.
    /// The four-step creation/destruction phase has one absolute deadline.
    pub fn poll(self: *Owner) Error!?exchange.Dispatch {
        if (self.state != .creating and self.state != .destroying) return error.State;
        self.exchange.guard(self.deadline) catch |err| return self.fail(err);
        if (self.exchange.pending != null) return error.Pending;
        if (self.outstanding == null) {
            var operation: ?Operation = null;
            if (self.state == .creating) {
                for (self.slots, 0..) |slot, i| {
                    if (slot == .absent) {
                        operation = .{ .allocate = @enumFromInt(i) };
                        break;
                    }
                    if (slot != .live) return self.fail(error.State);
                }
            } else {
                var i: usize = self.slots.len;
                while (i > 0) {
                    i -= 1;
                    if (self.slots[i] == .live) {
                        operation = .{ .free = @enumFromInt(i) };
                        break;
                    }
                    if (self.slots[i] != .absent) return self.fail(error.State);
                }
            }
            if (operation) |value| {
                const request = try encode(&self.plan, value, &self.request_bytes);
                self.exchange.begin(request.function, request.bytes, self.deadline) catch |err| return self.fail(err);
                const kind = switch (value) {
                    .allocate, .free => |item| item,
                };
                self.slots[@intFromEnum(kind)] = if (value == .allocate) .creating else .freeing;
                self.outstanding = value;
            } else {
                self.state = if (self.state == .creating) .objects_ready else .objects_closed;
                return null;
            }
        }
        const dispatch = (self.exchange.poll(self.deadline) catch |err| return self.fail(err)) orelse return null;
        if (!dispatch.response) return dispatch;
        const operation = self.outstanding.?;
        const response = decode(&self.plan, operation, dispatch.record) catch |err| return self.fail(err);
        self.last_status = .{ .operation = operation, .result = response };
        // RPC-level failure does not prove whether the object operation ran.
        // Retain the unacknowledged receipt and all ancestor names on ambiguity.
        if (response == .rpc_error) return self.fail(error.FirmwareResult);
        self.exchange.complete(dispatch.ticket) catch |err| return self.fail(err);
        const kind = switch (operation) {
            .allocate, .free => |value| value,
        };
        if (response == .rm_error) {
            if (operation == .allocate) {
                self.slots[@intFromEnum(kind)] = .absent;
                self.outstanding = null;
                self.state = .rejected; // Explicit cleanup may release proven ancestors.
                return null;
            }
            // A failed free never authorizes freeing its parent or name reuse.
            return self.fail(error.FirmwareResult);
        }
        self.slots[@intFromEnum(kind)] = if (operation == .allocate) .live else .absent;
        self.outstanding = null;
        if (operation == .allocate and kind == .display) self.state = .objects_ready;
        if (operation == .free and kind == .client) self.state = .objects_closed;
        return null;
    }
    pub fn borrowNotification(self: *Owner, ticket: exchange.transport.Ticket) Error!exchange.Dispatch {
        if (self.state != .creating and self.state != .destroying) return error.State;
        const item = self.exchange.borrow(ticket) catch |err| {
            if (err == error.Stale and self.exchange.phase != .failed) return err;
            return self.fail(err);
        };
        if (item.response) return error.Unexpected;
        return item;
    }
    pub fn completeNotification(self: *Owner, ticket: exchange.transport.Ticket) Error!void {
        _ = try self.borrowNotification(ticket);
        self.exchange.complete(ticket) catch |err| return self.fail(err);
    }
    pub fn rejectNotification(self: *Owner, ticket: exchange.transport.Ticket) Error!void {
        _ = try self.borrowNotification(ticket);
        return self.fail(error.Handler);
    }
    pub fn loan(self: *Owner, deadline: u64) Error!Loan {
        if (self.state != .objects_ready or self.outstanding != null) return error.State;
        for (self.slots) |slot| if (slot != .live) return error.State;
        const runtime = try self.exchange.handoff(deadline);
        self.state = .loaned;
        return .{ .runtime = runtime, .object = .{ .epoch = self.plan.epoch, .client = self.plan.handles.client, .display = self.plan.handles.display } };
    }
    pub fn reclaim(self: *Owner, runtime: *boot.Handoff, deadline: u64) Error!void {
        if (self.state != .loaned) return error.State;
        if (runtime.session != self.exchange.session or runtime.session.epoch != self.plan.epoch) return error.Handle;
        self.exchange = try exchange.Exchange.init(runtime, deadline);
        self.state = .objects_ready;
    }
    /// A confirmed allocation rejection permits a new explicit cleanup budget
    /// for the already-live prefix. A timeout/protocol/ACK failure does not.
    pub fn beginDestroy(self: *Owner, deadline: u64) Error!void {
        if (self.state != .objects_ready and self.state != .rejected) return error.State;
        if (self.outstanding != null or self.exchange.phase != .idle or self.exchange.pending != null) return error.State;
        self.exchange.guard(deadline) catch |err| return self.fail(err);
        self.deadline = deadline;
        self.state = .destroying;
    }
    /// All four RM names were explicitly freed/rejected. The returned runtime
    /// still owns active firmware and DMA queues; objects_closed is not a
    /// device-quiescence or backing-release certificate.
    pub fn finish(self: *Owner, deadline: u64) Error!boot.Handoff {
        if (self.state != .objects_closed) return error.State;
        const runtime = try self.exchange.handoff(deadline);
        self.state = .finished;
        return runtime;
    }
};
