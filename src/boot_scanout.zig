//! Held GA106 display-state observation for boot takeover/recovery planning.
//! Reads only fused topology and the armed method-state mirrors. This neither
//! proves visible scanout nor supplies a restore recipe or modeset authority.
// Mirror offsets/GA106 dispatch: Nouveau ga102/gv100 (MIT). Field meanings:
// NVIDIA 570.144 C67D/C67E and NVKMS (MIT). Original R4OS lifetime/validation: Apache-2.0.
const std = @import("std");
const r4os = @import("r4os");
const identity = @import("identity.zig");
const state = @import("fwsec_state.zig");
const bar0 = @import("bar0.zig");
const display_context = @import("display_context.zig");
pub const max_heads = 8;
pub const max_sors = 8;
pub const max_windows = 8;
pub const capability_register: u32 = 0x610060;
pub const window_capability_register: u32 = 0x610064;
pub const count_register: u32 = 0x610074;
pub const armed_base: u32 = 0x688000;
// C67D methods in the armed RAM mirror, not channel submit addresses.
pub const head_methods = [_]u32{ 0x2004, 0x2008, 0x200c, 0x201c, 0x204c, 0x2058, 0x2064, 0x2068, 0x206c, 0x2070 };
pub const Field = enum { output, control, clock, clock_config, viewport_in, viewport_out, total, sync_end, blank_end, blank_start };
pub const window_core_methods = [_]u32{ 0x1000, 0x1004, 0x1008, 0x100c, 0x1010 };
pub const window_armed_base: u32 = 0x690800;
pub const window_methods = [_]u32{
    0x224, 0x228, 0x22c, 0x230, 0x234, 0x238,
    0x240, 0x244, 0x248, 0x24c, 0x250, 0x254,
    0x260, 0x264, 0x268, 0x26c, 0x270, 0x274,
    0x290, 0x298, 0x2a4, 0x2a8, 0x2ec, 0x2f0,
    0x2f4, 0x308, 0x294,
};
pub const WindowField = enum {
    size,
    storage,
    params,
    pitch0,
    pitch1,
    pitch2,
    dma0,
    dma1,
    dma2,
    dma3,
    dma4,
    dma5,
    offset0,
    offset1,
    offset2,
    offset3,
    offset4,
    offset5,
    point_left,
    input,
    output,
    scaler,
    composition,
    alpha,
    factors,
    present,
    point_right,
};
pub const Window = struct {
    client: u32 = 0,
    core: [window_core_methods.len]u32 = @splat(0),
    words: [window_methods.len]u32 = @splat(0),
    pub fn get(self: *const Window, field: WindowField) u32 {
        return self.words[@intFromEnum(field)];
    }
    /// Context-relative offsets, never physical or BAR1 addresses. Layout and
    /// pitch units require the ISO context descriptor, not SET_STORAGE.
    pub fn binding(self: *const Window, plane: u2, eye: u1) !Binding {
        if (plane >= 3) return error.Plane;
        const index = @as(usize, eye) + (@as(usize, plane) << 1);
        return .{ .handle = self.words[@intFromEnum(WindowField.dma0) + index], .offset_bytes = @as(u64, self.words[@intFromEnum(WindowField.offset0) + index]) << 8 };
    }
    pub fn dimensions(self: *const Window, field: WindowField) Size {
        const value = self.get(field);
        return .{ .x = @truncate(value), .y = @truncate(value >> 16) };
    }
};
pub const Binding = struct { handle: u32, offset_bytes: u64 };
pub fn windowHead(window: *const Window) !?u3 {
    const owner = window.core[0] & 15;
    if (owner == 15) return null;
    if (owner >= max_heads) return error.Routing;
    return @intCast(owner);
}
pub const max_read_count = 2 * (14 + max_sors + max_heads * (head_methods.len + 1) +
    max_windows * (1 + window_core_methods.len + window_methods.len));
pub const Head = struct {
    words: [head_methods.len]u32 = @splat(0),
    hdmi: u32 = 0,
    pub fn get(self: *const Head, field: Field) u32 {
        return self.words[@intFromEnum(field)];
    }
};
pub const Raw = struct {
    boot0: u32 = 0,
    boot1: u32 = 0,
    capabilities: u32 = 0,
    window_mask: u32 = 0,
    counts: u32 = 0,
    instance_control: u32 = 0,
    instance_address: u32 = 0,
    heads: [max_heads]Head = @splat(.{}),
    sors: [max_sors]u32 = @splat(0),
    windows: [max_windows]Window = @splat(.{}),
    pub fn headMask(self: *const Raw) u8 {
        return @truncate(self.capabilities);
    }
    pub fn sorMask(self: *const Raw) u8 {
        return @truncate(self.capabilities >> 8);
    }
    pub fn headCount(self: *const Raw) u4 {
        return @truncate(self.counts);
    }
    pub fn sorCount(self: *const Raw) u4 {
        return @truncate(self.counts >> 8);
    }
    pub fn windowCount(self: *const Raw) u6 {
        return @truncate(self.counts >> 20);
    }
};
pub const Protocol = enum { lvds, tmds_a, tmds_b, tmds_dual, dp_a, dp_b, hdmi_frl, custom, unknown };
pub fn protocol(value: u32) Protocol {
    return switch ((value >> 8) & 15) {
        0 => .lvds,
        1 => .tmds_a,
        2 => .tmds_b,
        5 => .tmds_dual,
        8 => .dp_a,
        9 => .dp_b,
        12 => .hdmi_frl,
        15 => .custom,
        else => .unknown,
    };
}
pub const Size = struct { x: u16, y: u16 };
fn size(value: u32) !Size {
    if (value & 0x80008000 != 0) return error.Coordinate;
    return .{ .x = @truncate(value), .y = @truncate(value >> 16) };
}
pub const Timing = struct {
    total: Size,
    sync_end: Size,
    blank_end: Size,
    blank_start: Size,
    active: Size,
    viewport_in: Size,
    viewport_out: Size,
    pixel_clock_numerator: u64,
    pixel_clock_denominator: u32,
    raster_micro_hz: u64,
    depth_code: u4,
    hsync_negative: bool,
    vsync_negative: bool,
    hdmi_enabled: bool,
};
/// Describe only progressive timing with defined, ordered coordinates. Keep
/// unsupported raw states in the snapshot without guessing their interpretation.
pub fn timing(head: *const Head) !Timing {
    if (head.get(.control) & 7 != 0) return error.Structure;
    const total = try size(head.get(.total));
    const sync = try size(head.get(.sync_end));
    const end = try size(head.get(.blank_end));
    const start = try size(head.get(.blank_start));
    if (total.x == 0 or total.y == 0 or sync.x >= end.x or sync.y >= end.y or
        end.x >= start.x or end.y >= start.y or start.x >= total.x or start.y >= total.y) return error.Timing;
    const input = try size(head.get(.viewport_in));
    const output = try size(head.get(.viewport_out));
    const clock = head.get(.clock);
    const hz = clock & 0x7fffffff;
    if (hz == 0) return error.Clock;
    const adjusted = clock & 0x80000000 != 0;
    const numerator = @as(u64, hz) * @as(u64, if (adjusted) 1000 else 1);
    const denominator: u32 = if (adjusted) 1001 else 1;
    return .{ .total = total, .sync_end = sync, .blank_end = end, .blank_start = start, .active = .{ .x = start.x - end.x, .y = start.y - end.y }, .viewport_in = input, .viewport_out = output, .pixel_clock_numerator = numerator, .pixel_clock_denominator = denominator, .raster_micro_hz = numerator * 1000000 / (@as(u64, denominator) * total.x * total.y), .depth_code = @truncate(head.get(.output) >> 4), .hsync_negative = head.get(.output) & 4 != 0, .vsync_negative = head.get(.output) & 8 != 0, .hdmi_enabled = head.hdmi & 0x40000000 != 0 };
}
pub fn routedHeads(raw: *const Raw) u8 {
    var heads: u8 = 0;
    for (0..max_sors) |index| if (raw.sorMask() & (@as(u8, 1) << @intCast(index)) != 0) {
        heads |= @truncate(raw.sors[index]);
    };
    return heads;
}
pub fn headSors(raw: *const Raw, head: usize) u8 {
    if (head >= max_heads) return 0;
    var mask: u8 = 0;
    for (0..max_sors) |index| if (raw.sorMask() & (@as(u8, 1) << @intCast(index)) != 0 and
        raw.sors[index] & (@as(u32, 1) << @intCast(head)) != 0)
    {
        mask |= @as(u8, 1) << @intCast(index);
    };
    return mask;
}
pub const Hold = struct {
    context: *anyopaque,
    epoch: u64,
    generation: *const fn (*anyopaque) u64,
};
pub const Capture = struct {
    self_address: usize = 0,
    access: bar0.Lease = .{},
    clock: ?r4os.r4dev.DriverResourceContext = null,
    hold: ?Hold = null,
    previous: u64 = 0,
    deadline: u64 = 0,
    reads: u32 = 0,
    // Resident passes; no maximum-state array copied onto the kernel stack.
    first: Raw = .{},
    second: Raw = .{},

    /// Caller owns the common boot hold; borrow its existing BAR0 map. On any
    /// error the same capture object must close its retained child lease.
    pub fn readShared(self: *Capture, ctx: *const r4os.r4dev.DriverContext, snapshot: *const identity.Snapshot, chip: identity.Chip, shared: *bar0.Owner, hold: Hold) !Raw {
        if (self.self_address != 0) return error.Busy;
        if (chip.id != 0x176 or hold.epoch == 0 or snapshot.pci.function != 0 or identity.decision(snapshot) != .identity_words_only) return error.Profile;
        self.self_address = @intFromPtr(self);
        self.clock = ctx.resources() orelse return error.Api;
        self.hold = hold;
        const now = self.clock.?.nowNs();
        if (now == 0 or now == std.math.maxInt(u64)) return error.Clock;
        self.previous = now;
        self.deadline = try std.math.add(u64, now, std.time.ns_per_s);
        try self.access.acquire(shared, ctx, snapshot, chip);
        try self.observe(&self.first, chip);
        try self.observe(&self.second, chip);
        if (!std.meta.eql(self.first, self.second)) return error.Unstable;
        try self.guard();
        return self.first;
    }
    fn guard(self: *Capture) !void {
        if (self.self_address != @intFromPtr(self) or !self.access.valid()) return error.Stale;
        const hold = self.hold orelse return error.Stale;
        if (hold.generation(hold.context) != hold.epoch) return error.Stale;
        const now = self.clock.?.nowNs();
        if (now == 0 or now == std.math.maxInt(u64) or now < self.previous) return error.Clock;
        self.previous = now;
        if (now >= self.deadline) return error.Deadline;
    }
    fn permitted(address: u32) bool {
        if (address == display_context.instance_control_register or address == display_context.instance_address_register) return true;
        if (address == 0 or address == 4 or address == capability_register or address == window_capability_register or address == count_register) return true;
        for (0..max_heads) |head| {
            const offset: u32 = @intCast(head * 0x400);
            for (head_methods) |method| if (address == armed_base + method + offset) return true;
            if (address == 0x6165c0 + head * 0x800) return true;
        }
        for (0..max_sors) |sor| if (address == armed_base + 0x300 + sor * 0x20) return true;
        for (0..max_windows) |window| {
            if (address == display_context.client_register + (1 + window) * 16) return true;
            for (window_core_methods) |method| if (address == armed_base + method + window * 0x80) return true;
            for (window_methods) |method| if (address == window_armed_base + method + window * 0x1000) return true;
        }
        return false;
    }
    fn read(self: *Capture, address: u32) !u32 {
        if (!permitted(address)) return error.Register;
        try self.guard();
        const view = try self.access.view(address, 4);
        const pointer: *volatile u32 = @ptrFromInt(view.cpu_address);
        asm volatile ("mfence" ::: .{ .memory = true });
        const value = pointer.*;
        asm volatile ("mfence" ::: .{ .memory = true });
        self.reads += 1;
        try self.guard();
        if (!state.readable(value)) return error.Inaccessible;
        return value;
    }
    fn observe(self: *Capture, out: *Raw, chip: identity.Chip) !void {
        out.boot0 = try self.read(0);
        out.boot1 = try self.read(4);
        const observed = identity.chip(out.boot0, out.boot1) orelse return error.Profile;
        if (observed.id != chip.id or observed.revision != chip.revision) return error.Unstable;
        out.capabilities = try self.read(capability_register);
        out.instance_control = try self.read(display_context.instance_control_register);
        out.instance_address = try self.read(display_context.instance_address_register);
        out.window_mask = try self.read(window_capability_register);
        out.counts = try self.read(count_register);
        if (out.headCount() == 0 or out.headCount() > max_heads or out.sorCount() == 0 or out.sorCount() > max_sors or
            out.windowCount() == 0 or out.windowCount() > max_windows or
            @as(u64, out.window_mask) >> out.windowCount() != 0 or
            @as(u16, out.headMask()) >> out.headCount() != 0 or @as(u16, out.sorMask()) >> out.sorCount() != 0) return error.Topology;
        for (0..max_sors) |sor| if (out.sorMask() & (@as(u8, 1) << @intCast(sor)) != 0) {
            out.sors[sor] = try self.read(armed_base + 0x300 + @as(u32, @intCast(sor)) * 0x20);
            if (out.sors[sor] & 0xff & ~@as(u32, out.headMask()) != 0) return error.Routing;
        };
        for (0..max_heads) |head| if (out.headMask() & (@as(u8, 1) << @intCast(head)) != 0) {
            const offset: u32 = @intCast(head * 0x400);
            for (head_methods, 0..) |method, index| out.heads[head].words[index] = try self.read(armed_base + method + offset);
            out.heads[head].hdmi = try self.read(0x6165c0 + @as(u32, @intCast(head)) * 0x800);
        };
        for (0..max_windows) |window| if (out.window_mask & (@as(u32, 1) << @intCast(window)) != 0) {
            const offset: u32 = @intCast(window);
            const target = &out.windows[window];
            target.client = try self.read(display_context.client_register + (1 + offset) * 16);
            for (window_core_methods, 0..) |method, index| target.core[index] = try self.read(armed_base + method + offset * 0x80);
            if (try windowHead(target)) |head| {
                if (out.headMask() & (@as(u8, 1) << head) == 0) return error.Routing;
            }
            for (window_methods, 0..) |method, index| target.words[index] = try self.read(window_armed_base + method + offset * 0x1000);
        };
        if (try self.read(0) != out.boot0 or try self.read(4) != out.boot1 or
            try self.read(capability_register) != out.capabilities or try self.read(window_capability_register) != out.window_mask or
            try self.read(count_register) != out.counts or try self.read(display_context.instance_control_register) != out.instance_control or
            try self.read(display_context.instance_address_register) != out.instance_address) return error.Unstable;
    }
    pub fn close(self: *Capture) bool {
        if (self.self_address == 0) return true;
        if (self.self_address != @intFromPtr(self) or !self.access.release()) return false;
        self.* = .{};
        return true;
    }
};
