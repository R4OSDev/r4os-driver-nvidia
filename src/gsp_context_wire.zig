//! Pinned RM context and engine-discovery protocol. No hardware addresses are
//! invented from runlist IDs; topology fields remain descriptive until used
//! by their specific, validated channel/interrupt owner.
const std = @import("std");
const exchange = @import("gsp_exchange.zig");
pub const Error = exchange.Error || error{Unsupported};
pub const graphics = @import("gsp_gr_context.zig");
pub const Operation = enum { classes, engines, copy_caps, method_size, graphics_info, falcon_info, group, timeslice, share, free_share, free_group };
pub const timeslice = @import("gsp_timeslice.zig");
pub const max_bytes: usize = 3236;
pub const Binding = struct { epoch: u64, client: u32, device: u32, subdevice: u32, vaspace: u32, group: u32, share: u32, internal_client: u32 = 0, internal_subdevice: u32 = 0 };
pub const Engine = struct { data: [16]u32, pbdma: [2]u32, faults: [2]u32, count: u32, name: [16]u8 };
/// ctrl2080ce.h / kceGetDeviceCaps_IMPL: physical firmware capabilities.
/// GRCE is synchronous with GR; SYSMEM admits system-memory transfers.
/// The public GET_CAPS_V2 is host implemented, not a GSP control endpoint.
pub const CopyCaps = struct {
    bytes: [2]u8,
    pub fn grce(self: CopyCaps) bool { return self.bytes[0] & 0x01 != 0; }
    pub fn sysmem(self: CopyCaps) bool { return self.bytes[0] & 0x20 != 0; }
    pub fn standalone(self: CopyCaps) bool { return !self.grce() and self.sysmem(); }
};
/// RM 570 has COPY0..COPY19. Only a CE on GR's actual runlist may be
/// instantiated on its channel (Nouveau r535/fifo.c). Enumeration order and
/// the NV2080 numbering gap at COPY10 must not choose the engine for us.
pub const CopyTopology = struct {
    const Row = struct { present: bool = false, runlist: u32 = 0, base: u32 = 0, count: u32 = 0, pbdma: [2]u32 = .{ 0, 0 } };
    rows: [20]Row = @splat(.{}),
    pub fn add(self: *CopyTopology, value: Engine) Error!void {
        const rm = value.data[2];
        if (rm < 9 or rm > 28) return;
        const row = &self.rows[rm - 9];
        if (row.present) return error.Payload;
        row.* = .{ .present = true, .runlist = value.data[3], .base = value.data[11], .count = value.count, .pbdma = value.pbdma };
    }
    pub fn paired(self: *const CopyTopology, gr: Engine) ?u32 {
        if (gr.data[2] != 1 or gr.count == 0 or gr.count > 2 or
            gr.data[3] == 0xffffffff or gr.data[11] == 0 or
            gr.data[11] == 0xffffffff or gr.data[11] & 3 != 0) return null;
        for (&self.rows, 0..) |*row, index| {
            if (!row.present or row.runlist != gr.data[3] or row.base != gr.data[11] or
                row.count == 0 or row.count > row.pbdma.len) continue;
            // RM _kfifoIsValidCETag_GP102 accepts any shared PBDMA. Counts
            // and enumeration order are engine-local, not runlist identity.
            for (row.pbdma[0..row.count]) |copy_dma| {
                for (gr.pbdma[0..gr.count]) |graphics_dma| {
                    if (copy_dma == graphics_dma) return @intCast(9 + index);
                }
            }
        }
        return null;
    }
};
pub const Reply = union(enum) { rejected: u32, ok: []const u8 };
pub fn nvEngine(rm: u32) Error!u32 {
    return if (rm >= 1 and rm <= 18) rm else if (rm >= 19 and rm <= 28) rm - 19 + 0x34
        else if (rm >= 29 and rm <= 36) rm - 29 + 0x13
        else if (rm >= 37 and rm <= 39) rm - 37 + 0x1b
        else if (rm == 40) 0x3f else error.Unsupported;
}
pub fn nvdecInstance(rm: u32) Error!u32 {
    return if (rm >= 29 and rm <= 36) rm - 29 else error.Unsupported;
}
pub fn nvencInstance(rm: u32) Error!u32 {
    return if (rm >= 37 and rm <= 40) rm - 37 else error.Unsupported;
}
// ctrl2080gpu.h 570.144, independently evaluated by the original-header C
// fixture. r570_fifo_ectx_size queries the internal physical RM subdevice,
// matches ENGINE_INFO_TYPE_ENG_DESC (engine.data[0]), and uses the exact size.
pub const falcon_info_bytes: usize = 1284;
pub const max_falcon_bytes: u32 = 64 * 1024 * 1024; // Bounded private-context admission, not a hardware size.
pub fn videoEngine(rm: u32) bool { return rm >= 29 and rm <= 40; }
pub const FalconPromotion = struct {
    address: u64,
    bytes: u64,
    pub fn validate(self: FalconPromotion) Error!void {
        if (self.address == 0 or self.address & 4095 != 0 or self.bytes == 0 or self.bytes > max_falcon_bytes or
            self.address >= (@as(u64, 1) << 40) or self.bytes > (@as(u64, 1) << 40) - self.address) return error.Bounds;
    }
};
pub fn falconBytes(payload: []const u8, engine_desc: u32) Error!u32 {
    if (payload.len != falcon_info_bytes) return error.Payload;
    const count = word(payload, 0);
    if (count > 64) return error.Bounds;
    var found: ?u32 = null;
    for (0..count) |i| {
        const at = 4 + i * 20;
        if (word(payload, at) != engine_desc) continue;
        if (found != null) return error.Payload;
        found = word(payload, at + 8);
    }
    const bytes = found orelse return error.Unsupported;
    if (bytes == 0) return error.Unsupported;
    if (bytes > max_falcon_bytes) return error.Bounds;
    return bytes;
}
pub fn function(op: Operation) u32 { return switch (op) { .classes, .engines, .copy_caps, .method_size, .graphics_info, .falcon_info, .timeslice => 76, .group, .share => 103, .free_share, .free_group => 10 }; }
pub fn command(op: Operation) u32 { return switch (op) { .classes => 0x800292, .engines => 0x20801112, .copy_caps => 0x20802a07, .method_size => 0x20802a08, .graphics_info => 0x20800a32, .falcon_info => 0x208001b0, .timeslice => timeslice.command, else => 0 }; }
pub fn length(op: Operation) usize { return switch (op) { .classes => 428, .engines => max_bytes, .copy_caps => 32, .method_size => 28, .graphics_info => 24 + graphics.info_bytes, .falcon_info => 24 + falcon_info_bytes, .timeslice => 32, .group => 52, .share => 44, .free_share, .free_group => 16 }; }
pub fn word(data: []const u8, at: usize) u32 { return std.mem.readInt(u32, data[at..][0..4], .little); }
fn put(out: []u8, at: usize, value: u32) void { std.mem.writeInt(u32, out[at..][0..4], value, .little); }
pub fn validate(binding: Binding) Error!void {
    if (binding.epoch == 0) return error.Stale;
    const handles = [_]u32{binding.client,binding.device,binding.subdevice,binding.vaspace,binding.group,binding.share};
    for (handles, 0..) |handle, i| {
        if (handle == 0) return error.Handle;
        for (handles[0..i]) |prior| if (prior == handle) return error.Handle;
    }
}
pub fn encode(binding: Binding, rm_engine: u32, base: u32, op: Operation, output: []u8) Error![]const u8 {
    try validate(binding);
    const engine_type = try nvEngine(rm_engine);
    if (base >= 256 or base % 32 != 0 or output.len < length(op)) return error.Bounds;
    const out = output[0..length(op)]; @memset(out, 0);
    put(out, 0, binding.client);
    switch (op) {
        .classes, .engines, .method_size => {
            put(out, 4, if (op == .classes) binding.device else binding.subdevice);
            put(out, 8, command(op)); put(out, 16, @intCast(out.len - 24));
            if (op == .engines) put(out, 24, base);
        },
        .copy_caps => {
            if (rm_engine < 9 or rm_engine > 28) return error.Unsupported;
            if (binding.internal_client == 0 or binding.internal_subdevice == 0 or binding.internal_client == binding.client) return error.Handle;
            put(out, 0, binding.internal_client); put(out, 4, binding.internal_subdevice);
            put(out, 8, command(op)); put(out, 16, 8); put(out, 24, engine_type);
        },
        .graphics_info => {
            if (rm_engine != 1 or binding.internal_client == 0 or binding.internal_subdevice == 0 or binding.internal_client == binding.client) return error.Handle;
            put(out, 0, binding.internal_client); put(out, 4, binding.internal_subdevice);
            put(out, 8, command(op)); put(out, 16, graphics.info_bytes);
        },
        .falcon_info => {
            if (!videoEngine(rm_engine)) return error.Unsupported;
            if (binding.internal_client == 0 or binding.internal_subdevice == 0 or binding.internal_client == binding.client) return error.Handle;
            put(out, 0, binding.internal_client); put(out, 4, binding.internal_subdevice);
            put(out, 8, command(op)); put(out, 16, falcon_info_bytes);
        },
        .timeslice => {
            put(out, 4, binding.group); put(out, 8, command(op)); put(out, 16, 8);
            std.mem.writeInt(u64, out[24..32], timeslice.requested_us, .little);
        },
        .group, .share => {
            put(out, 4, if (op == .group) binding.device else binding.group);
            put(out, 8, if (op == .group) binding.group else binding.share);
            put(out, 12, if (op == .group) 0xa06c else 0x9067);
            put(out, 20, @intCast(out.len - 32));
            if (op == .group) { put(out, 40, binding.vaspace); put(out, 44, engine_type); }
            else put(out, 32, binding.vaspace); // Synchronous share; no caller-selected subcontext ID.
        },
        .free_share, .free_group => put(out, 8, if (op == .free_share) binding.share else binding.group),
    }
    return out;
}
pub fn decode(binding: Binding, rm_engine: u32, base: u32, op: Operation, request: []const u8, record: exchange.message.Record) Error!Reply {
    try validate(binding); _ = try nvEngine(rm_engine);
    if (base >= 256 or base % 32 != 0 or request.len != length(op) or record.rpc.function != function(op) or record.rpc.cpu_rm_gfid != 0) return error.Payload;
    if (record.rpc.result != 0) return error.FirmwareResult;
    const header: usize = if (function(op) == 76) 24 else if (function(op) == 103) 32 else 16;
    const data = record.payload;
    if (data.len != header and data.len != request.len) return error.Payload;
    const status_at: usize = if (function(op) == 103) 16 else 12;
    for (data[0..header], 0..) |value, i| {
        if (i >= status_at and i < status_at + 4) continue;
        if (value != request[i]) return error.Unexpected;
    }
    const status = word(data, status_at);
    if (status != 0) return .{ .rejected = status };
    if (data.len != request.len) return error.Payload;
    const payload = data[header..];
    switch (op) {
        .classes => if (word(payload, 0) > 100) return error.Bounds,
        .engines => {
            const count = word(payload, 4);
            if (word(payload, 0) != base or count > 32 or payload[8] > 1 or (base == 224 and payload[8] != 0)) return error.Bounds;
            for (0..count) |i| if (word(payload, 12 + i * 100 + 80) > 2) return error.Bounds;
        },
        .method_size => if (word(payload, 0) == 0) return error.Bounds,
        .copy_caps => if (rm_engine < 9 or rm_engine > 28 or word(payload, 0) != try nvEngine(rm_engine)) return error.Payload,
        .graphics_info => {}, // The context owner validates the bounded GR0 plan before ACK.
        .falcon_info => if (!videoEngine(rm_engine) or word(payload, 0) > 64) return error.Bounds,
        .group, .timeslice => if (!std.mem.eql(u8, payload, request[header..])) return error.Payload,
        .share => {
            if (!std.mem.eql(u8, payload[0..8], request[header..][0..8]) or word(payload, 8) & 0x80000000 != 0) return error.Payload;
        },
        .free_share, .free_group => {},
    }
    return .{ .ok = payload };
}
pub fn supports(data: []const u8, class: u32) bool {
    for (0..word(data, 0)) |i| if (word(data, 4 + i * 4) == class) return true;
    return false;
}
pub fn engine(data: []const u8, index: usize) Engine {
    const row = data[12 + index * 100..][0..100];
    var result: Engine = undefined;
    for (&result.data, 0..) |*v, i| v.* = word(row, i * 4);
    for (&result.pbdma, 0..) |*v, i| v.* = word(row, 64 + i * 4);
    for (&result.faults, 0..) |*v, i| v.* = word(row, 72 + i * 4);
    result.count = word(row, 80); result.name = row[84..100].*;
    return result;
}
