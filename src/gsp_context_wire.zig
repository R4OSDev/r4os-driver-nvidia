//! Pinned RM context and engine-discovery protocol. No hardware addresses are
//! invented from runlist IDs; topology fields remain descriptive until used
//! by their specific, validated channel/interrupt owner.
const std = @import("std");
const exchange = @import("gsp_exchange.zig");
pub const Error = exchange.Error || error{Unsupported};
pub const Operation = enum { classes, engines, method_size, group, share, free_share, free_group };
pub const max_bytes: usize = 3236;
pub const Binding = struct { epoch: u64, client: u32, device: u32, subdevice: u32, vaspace: u32, group: u32, share: u32 };
pub const Engine = struct { data: [16]u32, pbdma: [2]u32, faults: [2]u32, count: u32, name: [16]u8 };
pub const Reply = union(enum) { rejected: u32, ok: []const u8 };
pub fn nvEngine(rm: u32) Error!u32 {
    return if (rm >= 1 and rm <= 18) rm else if (rm >= 19 and rm <= 28) rm - 19 + 0x34 else error.Unsupported;
}
pub fn function(op: Operation) u32 { return switch (op) { .classes, .engines, .method_size => 76, .group, .share => 103, .free_share, .free_group => 10 }; }
pub fn command(op: Operation) u32 { return switch (op) { .classes => 0x800292, .engines => 0x20801112, .method_size => 0x20802a08, else => 0 }; }
pub fn length(op: Operation) usize { return switch (op) { .classes => 428, .engines => max_bytes, .method_size => 28, .group => 52, .share => 44, .free_share, .free_group => 16 }; }
pub fn word(data: []const u8, at: usize) u32 { return std.mem.readInt(u32, data[at..][0..4], .little); }
fn put(out: []u8, at: usize, value: u32) void { std.mem.writeInt(u32, out[at..][0..4], value, .little); }
pub fn validate(binding: Binding) Error!void {
    if (binding.epoch == 0) return error.Stale;
    const handles = [_]u32{binding.client,binding.device,binding.subdevice,binding.vaspace,binding.group,binding.share};
    for (handles, 0..) |handle, i| {
        if (handle == 0) return error.Handle;
        for (handles[0..i]) |prior| if (prior == handle) return error.Handle;
    }
}
pub fn encode(binding: Binding, rm_engine: u32, base: u32, op: Operation, output: []u8) Error![]const u8 {
    try validate(binding);
    const engine_type = try nvEngine(rm_engine);
    if (base >= 256 or base % 32 != 0 or output.len < length(op)) return error.Bounds;
    const out = output[0..length(op)]; @memset(out, 0);
    put(out, 0, binding.client);
    switch (op) {
        .classes, .engines, .method_size => {
            put(out, 4, if (op == .classes) binding.device else binding.subdevice);
            put(out, 8, command(op)); put(out, 16, @intCast(out.len - 24));
            if (op == .engines) put(out, 24, base);
        },
        .group, .share => {
            put(out, 4, if (op == .group) binding.device else binding.group);
            put(out, 8, if (op == .group) binding.group else binding.share);
            put(out, 12, if (op == .group) 0xa06c else 0x9067);
            put(out, 20, @intCast(out.len - 32));
            if (op == .group) { put(out, 40, binding.vaspace); put(out, 44, engine_type); }
            else put(out, 32, binding.vaspace); // Synchronous share; no caller-selected subcontext ID.
        },
        .free_share, .free_group => put(out, 8, if (op == .free_share) binding.share else binding.group),
    }
    return out;
}
pub fn decode(binding: Binding, rm_engine: u32, base: u32, op: Operation, request: []const u8, record: exchange.message.Record) Error!Reply {
    try validate(binding); _ = try nvEngine(rm_engine);
    if (base >= 256 or base % 32 != 0 or request.len != length(op) or record.rpc.function != function(op) or record.rpc.cpu_rm_gfid != 0) return error.Payload;
    if (record.rpc.result != 0) return error.FirmwareResult;
    const header: usize = if (function(op) == 76) 24 else if (function(op) == 103) 32 else 16;
    const data = record.payload;
    if (data.len != header and data.len != request.len) return error.Payload;
    const status_at: usize = if (function(op) == 103) 16 else 12;
    for (data[0..header], 0..) |value, i| {
        if (i >= status_at and i < status_at + 4) continue;
        if (value != request[i]) return error.Unexpected;
    }
    const status = word(data, status_at);
    if (status != 0) return .{ .rejected = status };
    if (data.len != request.len) return error.Payload;
    const payload = data[header..];
    switch (op) {
        .classes => if (word(payload, 0) > 100) return error.Bounds,
        .engines => {
            const count = word(payload, 4);
            if (word(payload, 0) != base or count > 32 or payload[8] > 1 or (base == 224 and payload[8] != 0)) return error.Bounds;
            for (0..count) |i| if (word(payload, 12 + i * 100 + 80) > 2) return error.Bounds;
        },
        .method_size => if (word(payload, 0) == 0) return error.Bounds,
        .group => if (!std.mem.eql(u8, payload, request[header..])) return error.Payload,
        .share => {
            if (!std.mem.eql(u8, payload[0..8], request[header..][0..8]) or word(payload, 8) & 0x80000000 != 0) return error.Payload;
        },
        .free_share, .free_group => {},
    }
    return .{ .ok = payload };
}
pub fn supports(data: []const u8, class: u32) bool {
    for (0..word(data, 0)) |i| if (word(data, 4 + i * 4) == class) return true;
    return false;
}
pub fn engine(data: []const u8, index: usize) Engine {
    const row = data[12 + index * 100..][0..100];
    var result: Engine = undefined;
    for (&result.data, 0..) |*v, i| v.* = word(row, i * 4);
    for (&result.pbdma, 0..) |*v, i| v.* = word(row, 64 + i * 4);
    for (&result.faults, 0..) |*v, i| v.* = word(row, 72 + i * 4);
    result.count = word(row, 80); result.name = row[84..100].*;
    return result;
}
