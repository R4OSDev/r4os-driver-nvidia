//! RM context owner for later FIFO channels. The group binds a confirmed
//! engine/runlist and the existing VA space; no FIFO is allocated or enabled
//! here. Child holders must end before context/share and group destruction.
const std = @import("std");
const boot = @import("gsp_boot_events.zig");
const exchange = @import("gsp_exchange.zig");
const names = @import("gsp_rm_names.zig");
const vram = @import("gsp_vram.zig");
pub const wire = @import("gsp_context_wire.zig");
pub const Error = wire.Error || names.Error || vram.Error || error{Retained, Busy};
pub const State = enum { creating, unwinding, ready, handed_off, destroying, closed, finished, failed };
pub const Unavailable = enum { classes, engine };
pub const Info = struct { binding: wire.Binding, rm_engine: u32, nv_engine: u32, engine: wire.Engine, method_bytes: u32, subcontext: u32 };
pub const Child = struct { epoch: u64, group: u32, serial: u64 };
pub const Owner = struct {
    self_address: usize = 0,
    exchange: exchange.Exchange,
    binding: wire.Binding,
    reservation: names.Children,
    namespace_live: bool = true,
    state: State = .creating,
    rm_engine: u32,
    classes: bool = false,
    engines: bool = false,
    base: u32 = 0,
    selected: ?wire.Engine = null,
    method_bytes: u32 = 0,
    subcontext: u32 = 0,
    group_live: bool = false,
    share_live: bool = false,
    child_serial: u64 = 0,
    children: [64]u64 = @splat(0),
    methods: [2]vram.storage.Use = @splat(.{}),
    request: [wire.max_bytes]u8 = undefined,
    operation: ?wire.Operation = null,
    rejected: ?u32 = null,
    last_status: ?u32 = null,
    unavailable: ?Unavailable = null,
    failure: ?Error = null,
    protocol_failure: ?exchange.Error = null,
    deadline: u64,

    pub fn init(token: *boot.Handoff, parent: names.Lease, space: @import("gsp_vaspace.zig").Info, subdevice: u32, rm_engine: u32, deadline: u64) Error!Owner {
        _ = try wire.nvEngine(rm_engine);
        if (token.claimed or token.session.state != .active or token.session.pending != null or
            space.epoch != token.session.epoch or parent.epoch != space.epoch or parent.client != space.client) return error.Stale;
        try token.session.guard(deadline);
        const children = try token.session.rm_names.reserveChildren(parent, 2);
        errdefer token.session.rm_names.retireChildren(children) catch {};
        const binding: wire.Binding = .{ .epoch = space.epoch, .client = space.client, .device = space.device, .subdevice = subdevice,
            .vaspace = space.handle, .group = try children.object(0), .share = try children.object(1) };
        try wire.validate(binding);
        return .{ .exchange = try exchange.Exchange.init(token, deadline), .binding = binding, .reservation = children, .rm_engine = rm_engine, .deadline = deadline };
    }
    fn stable(self: *const Owner) Error!void {
        if ((self.self_address != 0 and self.self_address != @intFromPtr(self)) or self.binding.epoch != self.exchange.session.epoch) return error.Stale;
        if (self.namespace_live) try self.exchange.session.rm_names.validateChildren(self.reservation);
    }
    fn fail(self: *Owner, err: Error) Error {
        self.failure = err; self.state = .failed;
        if (self.namespace_live) self.exchange.session.rm_names.retainChildren(self.reservation) catch {};
        self.protocol_failure = self.exchange.fail(error.Handler); return err;
    }
    pub fn info(self: *const Owner) ?Info {
        self.stable() catch return null;
        if (self.self_address != @intFromPtr(self) or !self.share_live or self.exchange.session.state != .active or
            (self.state != .ready and self.state != .handed_off)) return null;
        return .{ .binding = self.binding, .rm_engine = self.rm_engine, .nv_engine = wire.nvEngine(self.rm_engine) catch return null,
            .engine = self.selected orelse return null, .method_bytes = self.method_bytes, .subcontext = self.subcontext };
    }
    pub fn retainChild(self: *Owner) Error!Child {
        if (self.info() == null or self.state != .handed_off) return error.State;
        for (&self.children) |*slot| if (slot.* == 0) {
            self.child_serial = std.math.add(u64, self.child_serial, 1) catch return error.Exhausted;
            slot.* = self.child_serial;
            return .{ .epoch = self.binding.epoch, .group = self.binding.group, .serial = self.child_serial };
        };
        return error.Exhausted;
    }
    pub fn attachMethods(self: *Owner, runqueue: u8, source: *vram.Owner) Error!void {
        const context = self.info() orelse return error.State;
        if (self.state != .handed_off or self.held()) return error.Busy;
        if (runqueue >= self.methods.len or runqueue >= context.engine.count) return error.Bounds;
        if (self.methods[runqueue].self_address != 0) return error.Busy;
        const source_info = source.info() orelse return error.State;
        const space = source.binding.space;
        if (space.epoch != self.binding.epoch or space.client != self.binding.client or space.device != self.binding.device or
            space.handle != self.binding.vaspace) return error.Stale;
        if (source_info.logical_bytes != self.method_bytes) return error.Bounds;
        source.retainStorage(&self.methods[runqueue]) catch |err| {
            if (err == error.Descriptor or err == error.Retained) return self.fail(err);
            return err;
        };
    }
    pub fn methodStorage(self: *const Owner, runqueue: u8) ?vram.storage.Source {
        if (self.info() == null or runqueue >= self.methods.len) return null;
        return self.methods[runqueue].info();
    }
    pub fn releaseChild(self: *Owner, child: Child, quiesced: bool) Error!void {
        try self.stable();
        if (self.state != .handed_off or child.epoch != self.binding.epoch or child.group != self.binding.group or child.serial == 0) return error.Stale;
        for (&self.children) |*slot| if (slot.* == child.serial) {
            if (!quiesced) return error.Retained;
            slot.* = 0; return;
        };
        return error.Stale;
    }
    pub fn poll(self: *Owner) Error!?exchange.Dispatch {
        try self.stable();
        if (self.state != .creating and self.state != .unwinding and self.state != .destroying) return error.State;
        self.self_address = @intFromPtr(self);
        return self.advance() catch |err| { if (err == error.Pending) return err; return self.fail(err); };
    }
    fn advance(self: *Owner) Error!?exchange.Dispatch {
        try self.exchange.guard(self.deadline);
        if (self.exchange.pending != null) return error.Pending;
        if (self.operation == null) {
            const op: wire.Operation = if (self.state == .creating) blk: {
                if (!self.classes) break :blk .classes;
                if (!self.engines) break :blk .engines;
                if (self.method_bytes == 0) break :blk .method_size;
                if (!self.group_live) break :blk .group;
                if (!self.share_live) break :blk .share;
                self.state = .ready; return null;
            } else if (self.share_live) .free_share else if (self.group_live) .free_group else {
                // GSP installs the fault-method descriptor in the group.
                // It outlives individual channel objects and context shares.
                for (&self.methods) |*storage| if (!storage.close(true)) return error.Retained;
                if (self.namespace_live) { try self.exchange.session.rm_names.retireChildren(self.reservation); self.namespace_live = false; }
                self.state = if (self.state == .unwinding) .ready else .closed; return null;
            };
            const data = try wire.encode(self.binding, self.rm_engine, self.base, op, &self.request);
            try self.exchange.begin(wire.function(op), data, self.deadline); self.operation = op;
        }
        const dispatch = (try self.exchange.poll(self.deadline)) orelse return null;
        if (!dispatch.response) return dispatch;
        const op = self.operation.?;
        const reply = try wire.decode(self.binding, self.rm_engine, self.base, op, self.request[0..wire.length(op)], dispatch.record);
        // Validate the selected engine before ACK, publish its copy after ACK.
        var candidate = self.selected;
        if (op == .engines and reply == .ok) for (0..wire.word(reply.ok, 4)) |index| {
            const row = wire.engine(reply.ok, index);
            if (row.data[2] == self.rm_engine) {
                if (candidate != null or row.count == 0 or row.data[3] == 0xffffffff or row.data[11] == 0 or
                    row.data[11] == 0xffffffff or row.data[11] & 3 != 0) return error.Payload;
                candidate = row;
            }
        };
        const class_support = op == .classes and reply == .ok and wire.supports(reply.ok, 0xa06c) and wire.supports(reply.ok, 0x9067) and wire.supports(reply.ok, 0xc56f);
        const more = op == .engines and reply == .ok and reply.ok[8] != 0;
        const value: u32 = if (reply == .ok and op == .method_size) wire.word(reply.ok, 0)
            else if (reply == .ok and op == .share) wire.word(reply.ok, 8) else 0;
        self.last_status = if (reply == .rejected) reply.rejected else 0;
        try self.exchange.complete(dispatch.ticket);
        if (reply == .rejected) {
            if (self.state != .creating) return error.FirmwareResult;
            self.rejected = reply.rejected; self.state = .unwinding;
        } else switch (op) {
            .classes => {
                if (!class_support) {
                    self.unavailable = .classes; self.state = .unwinding;
                } else self.classes = true;
            },
            .engines => {
                self.selected = candidate;
                if (more) self.base += 32 else {
                    self.engines = true;
                    if (self.selected == null) { self.unavailable = .engine; self.state = .unwinding; }
                }
            },
            .method_size => self.method_bytes = value,
            .group => self.group_live = true,
            .share => { self.share_live = true; self.subcontext = value; },
            .free_share => self.share_live = false,
            .free_group => self.group_live = false,
        }
        self.operation = null; return null;
    }
    pub fn beginDestroy(self: *Owner, token: *boot.Handoff, deadline: u64) Error!void {
        try self.stable();
        if (self.state != .handed_off or token.session != self.exchange.session) return error.State;
        for (&self.children) |child| if (child != 0) return error.Retained;
        self.exchange = try exchange.Exchange.init(token, deadline); self.deadline = deadline; self.state = .destroying;
    }
    pub fn handoff(self: *Owner) Error!boot.Handoff {
        try self.stable();
        if (self.state != .ready and self.state != .closed) return error.State;
        const token = try self.exchange.handoff(self.deadline);
        self.state = if (self.state == .closed) .finished else .handed_off; return token;
    }
    pub fn held(self: *const Owner) bool {
        for (&self.children) |child| if (child != 0) return true;
        return false;
    }
    pub fn matches(self: *const Owner, channel: *const exchange.Exchange, deadline: u64) bool {
        self.stable() catch return false;
        const op = self.operation orelse return false;
        return self.self_address == @intFromPtr(self) and channel == &self.exchange and channel.deadline == deadline and self.deadline == deadline and
            channel.request.ptr == self.request[0..].ptr and channel.request.len == wire.length(op) and channel.function == wire.function(op) and
            (self.state == .creating or self.state == .unwinding or self.state == .destroying);
    }
};
