//! The actual runtime's fixed, read-only internal RM discovery sequence.
//! Firmware-owned handles remain borrowed. No RM allocation, IRQ registration,
//! engine enable, MMIO permission or device-memory release is granted here.
const std = @import("std");
const exchange = @import("gsp_exchange.zig");
const static = @import("gsp_static.zig");
const firmware = @import("firmware.zig");
pub const function: u32 = 76;
pub const header_bytes = 24;
pub const table_bytes = 2068;
pub const max_entries = 128;
pub const vector_invalid = std.math.maxInt(u32);
pub const vector_count = 8 * 32; // Published GA102 CPU interrupt leaf count.
pub const gsp_engine: u16 = 50;
pub const display_engine: u16 = 2;
pub const Command = enum(u32) { gpc = 0x20800137, tpc = 0x20800138, interrupts = 0x20800a5c };
pub const State = enum { detached, gpc, tpc, interrupts, complete };
pub const Entry = struct { engine: u16 = 0, pmc_mask: u32 = 0, stall: u32 = vector_invalid, nonstall: u32 = vector_invalid };
pub const Subtree = struct { first: u8 = 255, last: u8 = 255 };
pub const Data = struct {
    gpc_mask: u32 = 0,
    tpc_masks: [32]u32 = @splat(0),
    tpc_count: u32 = 0,
    entry_count: usize = 0,
    entries: [max_entries]Entry = @splat(.{}),
    subtrees: [7]Subtree = @splat(.{}),
    gsp_index: ?usize = null,
    display_index: ?usize = null,
};
comptime {
    if (!std.mem.eql(u8, firmware.lock.rm_version, "570.144") or
        !std.mem.eql(u8, firmware.lock.source_commit, "8ec351aeb96a93a4bb69ccc12a542bf8a8df2b6f"))
        @compileError("GSP post-init requires a new original-source ABI comparison");
}
fn get(comptime T: type, bytes: []const u8, offset: usize) T {
    return std.mem.readInt(T, bytes[offset..][0..@sizeOf(T)], .little);
}
fn put(bytes: []u8, offset: usize, value: u32) void {
    std.mem.writeInt(u32, bytes[offset..][0..4], value, .little);
}
pub const Owner = struct {
    self_address: usize = 0,
    channel: ?*exchange.Exchange = null,
    epoch: u64 = 0,
    client: u32 = 0,
    subdevice: u32 = 0,
    state: State = .detached,
    remaining: u32 = 0,
    gpc: u5 = 0,
    command: Command = .gpc,
    deadline: u64 = 0,
    armed: bool = false,
    request: [header_bytes + table_bytes]u8 = @splat(0),
    request_bytes: usize = 0,
    data: Data = .{}, // Resident staging; snapshot() exposes only complete data.
    replies: u32 = 0,
    last_status: ?u32 = null,
    failure: ?anyerror = null,

    pub fn open(self: *Owner, channel: *exchange.Exchange, info: *const static.Info) !void {
        if (self.self_address != 0 or channel.phase != .idle or channel.pending != null or
            channel.session.pending != null or channel.session.state != .active) return error.State;
        if (info.client == 0 or info.subdevice == 0) return error.Handle;
        self.self_address = @intFromPtr(self);
        self.channel = channel;
        self.epoch = channel.session.epoch;
        self.client = info.client;
        self.subdevice = info.subdevice;
        self.state = .gpc;
    }
    fn guard(self: *Owner) !*exchange.Exchange {
        if (self.self_address != @intFromPtr(self) or self.failure != null or self.channel == null) return error.State;
        const channel = self.channel.?;
        if (channel.session.epoch != self.epoch or channel.session.state != .active) return error.Stale;
        return channel;
    }
    pub fn prepare(self: *Owner, deadline: u64) !void {
        const channel = try self.guard();
        if (self.armed or channel.phase != .idle or channel.pending != null) return error.State;
        errdefer |err| self.failure = err;
        const size: usize = switch (self.state) {
            .gpc => 4,
            .tpc => 8,
            .interrupts => table_bytes,
            else => return error.State,
        };
        self.command = switch (self.state) { .gpc => .gpc, .tpc => .tpc, .interrupts => .interrupts, else => unreachable };
        self.request_bytes = header_bytes + size;
        const request = self.request[0..self.request_bytes];
        @memset(request, 0);
        put(request, 0, self.client);
        put(request, 4, self.subdevice);
        put(request, 8, @intFromEnum(self.command));
        put(request, 16, @intCast(size)); // Flags NONE, no FINN/pointer serialization.
        if (self.state == .tpc) put(request, header_bytes, self.gpc);
        self.deadline = deadline;
        self.last_status = null;
        try channel.begin(function, request, deadline);
        self.armed = true;
    }
    /// Pure admission by the outer actual device owner. No fabricated RM
    /// handles, foreign queue, different payload or second caller is admitted.
    pub fn matches(self: *const Owner, channel: *const exchange.Exchange, deadline: u64) bool {
        return self.self_address == @intFromPtr(self) and self.failure == null and self.armed and
            self.channel == channel and channel.session.epoch == self.epoch and channel.phase == .prepared and
            channel.function == function and self.deadline == deadline and channel.deadline == deadline and
            channel.request.ptr == self.request[0..].ptr and channel.request.len == self.request_bytes;
    }
    pub fn accept(self: *Owner, dispatch: exchange.Dispatch) !void {
        const channel = try self.guard();
        if (!self.armed or !dispatch.response or channel.phase != .waiting) return error.State;
        errdefer |err| self.failure = err;
        const received = try channel.borrow(dispatch.ticket);
        const record = received.record;
        if (!received.response or record.rpc.function != function) return error.Unexpected;
        if (record.rpc.cpu_rm_gfid != 0) return error.Guest;
        if (record.rpc.result == exchange.message.pending) return error.Payload;
        if (record.rpc.result != 0) return error.Rpc;
        const bytes = record.payload;
        if (bytes.len != self.request_bytes) return error.Payload;
        if (get(u32, bytes, 0) != self.client or get(u32, bytes, 4) != self.subdevice or
            get(u32, bytes, 8) != @intFromEnum(self.command)) return error.Unexpected;
        if (get(u32, bytes, 16) != self.request_bytes - header_bytes or get(u32, bytes, 20) != 0) return error.Payload;
        self.last_status = get(u32, bytes, 12);
        if (self.last_status.? != 0) return error.Control;
        const params = bytes[header_bytes..];
        // RPC sequence/private remain raw diagnostics, not an invented echo
        // contract. Returned handles, command and TPC selector identify data.
        const mask: u32 = switch (self.state) {
            .gpc => get(u32, params, 0),
            .tpc => blk: {
                if (get(u32, params, 0) != self.gpc) return error.Unexpected;
                break :blk get(u32, params, 4);
            },
            .interrupts => blk: { try self.decodeInterrupts(params); break :blk 0; },
            else => return error.State,
        };
        try channel.complete(dispatch.ticket);
        self.armed = false;
        self.replies += 1;
        switch (self.state) {
            .gpc => { self.data.gpc_mask = mask; self.remaining = mask; self.nextCluster(); },
            .tpc => {
                self.data.tpc_masks[self.gpc] = mask;
                self.data.tpc_count += @popCount(mask);
                self.remaining &= ~(@as(u32, 1) << self.gpc);
                self.nextCluster();
            },
            .interrupts => self.state = .complete,
            else => unreachable,
        }
    }
    fn nextCluster(self: *Owner) void {
        if (self.remaining == 0) { self.state = .interrupts; return; }
        self.gpc = @intCast(@ctz(self.remaining));
        self.state = .tpc;
    }
    fn decodeInterrupts(self: *Owner, bytes: []const u8) !void {
        const count = get(u32, bytes, 0);
        if (count > max_entries) return error.Table;
        self.data.entry_count = count;
        for (self.data.entries[0..count], 0..) |*entry, index| {
            const at = 4 + index * 16;
            entry.* = .{ .engine = get(u16, bytes, at), .pmc_mask = get(u32, bytes, at + 4),
                .stall = get(u32, bytes, at + 8), .nonstall = get(u32, bytes, at + 12) };
            for ([_]u32{entry.stall, entry.nonstall}) |vector|
                if (vector != vector_invalid and vector >= vector_count) return error.Vector;
            // Unknown engines retain their original bounded record. Only the
            // required GSP and optional display bindings are selected here.
            if (entry.engine == gsp_engine) {
                if (self.data.gsp_index != null or entry.stall == vector_invalid) return error.Vector;
                self.data.gsp_index = index;
            } else if (entry.engine == display_engine) {
                if (self.data.display_index != null) return error.Table;
                self.data.display_index = index;
            }
        }
        if (self.data.gsp_index == null) return error.Vector;
        for (&self.data.subtrees, 0..) |*subtree, index| {
            const at = 2052 + index * 2;
            subtree.* = .{ .first = bytes[at], .last = bytes[at + 1] };
            if (subtree.first == 255 and subtree.last == 255) continue;
            if (subtree.first > subtree.last or subtree.last >= vector_count / 64) return error.Table;
        }
    }
    /// Until every query and its ACK succeeded, no partially collected table
    /// can be consumed as a configured interrupt/engine inventory.
    pub fn snapshot(self: *const Owner) ?*const Data {
        if (self.self_address != @intFromPtr(self) or self.state != .complete or self.failure != null or
            self.channel == null or self.channel.?.session.epoch != self.epoch or self.channel.?.session.state != .active) return null;
        return &self.data;
    }
};
