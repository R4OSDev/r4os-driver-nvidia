//! Cursor and memory-LUT attachments resolved from the held display instance.
//! Pure metadata: targets remain GPU address spaces, never CPU pointers.
const std = @import("std");
const scanout = @import("boot_scanout.zig");
const context = @import("display_context.zig");
pub const max_assets = scanout.max_heads * 3 + scanout.max_windows * 2;
pub const max_payload_bytes = scanout.max_heads * 2 * 256 * 256 * 4 + (scanout.max_heads + scanout.max_windows * 2) * 2047 * 8;
pub const Kind = enum { cursor, olut, ilut, tmo };
pub const MemorySpan = struct { target: context.Target, span: context.Span };
pub const Asset = struct {
    kind: Kind,
    owner: u8,
    eye: u1,
    handle: u32,
    binding: context.Resolved,
    memory: MemorySpan,
    backup_offset: usize,
};

/// C67D cursor size is square, with packed rows (curs507a_acquire).
/// Disabled cursors may retain arbitrary old format/size/handle words.
pub fn cursorBytes(control: u32) !u64 {
    if (control & 0x80000000 == 0) return 0;
    if (control & ~@as(u32, 0x8ffff3ff) != 0) return error.AssetControl;
    const pixel_bytes: u64 = switch (control & 255) {
        0xcf => 4,
        0xe9 => 2,
        else => return error.AssetFormat,
    };
    const width: u64 = @as(u64, 32) << @as(u6, @intCast((control >> 8) & 3));
    return width * width * pixel_bytes;
}

/// SIZE already includes VSS headers and interpolation endpoint entries.
/// Each NVEvoLutEntryRec is four 16-bit components. Do not add a header twice.
pub fn lutBytes(kind: Kind, control: u32) !u64 {
    if (kind == .cursor) return error.AssetKind;
    const mask: u32 = if (kind == .tmo) 0x7ff0d else 0x7ff0f;
    if (control & ~mask != 0 or (kind != .tmo and (control >> 2) & 3 == 3)) return error.AssetControl;
    const entries = (control >> 8) & 2047;
    if (entries == 0) return error.AssetSize;
    return @as(u64, entries) * 8;
}

pub fn memorySpan(descriptor: context.Descriptor, offset_word: u32, bytes: u64, framebuffer_bytes: u64) !MemorySpan {
    if (descriptor.layout != .pitch) return error.AssetLayout;
    if (bytes == 0 or bytes > max_payload_bytes or descriptor.end <= descriptor.address) return error.AssetBounds;
    const address = std.math.add(u64, descriptor.address, @as(u64, offset_word) << 8) catch return error.AssetBounds;
    const end = std.math.add(u64, address, bytes) catch return error.AssetBounds;
    if (end > descriptor.end or address & 255 != 0) return error.AssetBounds;
    // System memory is in a different namespace; never apply the VRAM bound
    // or reinterpret its descriptor target as a BAR0_WINDOW target number.
    if (descriptor.target == .vram and (end > framebuffer_bytes or end > @as(u64, 1) << 40)) return error.AssetBounds;
    return .{ .target = descriptor.target, .span = .{ .address = address, .bytes = bytes } };
}

pub const Catalog = struct {
    items: [max_assets]Asset = undefined,
    count: usize = 0,
    bytes: usize = 0,

    fn add(self: *Catalog, instance: []const u8, client: u32, channel: u7, kind: Kind, owner: usize, eye: u1, handle: u32, offset: u32, bytes: u64, framebuffer_bytes: u64) !void {
        if (client & ~@as(u32, 0x3fff) != 0 or handle == 0) return error.AssetContext;
        const binding = try context.lookup(instance, @intCast(client), handle, channel);
        const memory = try memorySpan(binding.descriptor, offset, bytes, framebuffer_bytes);
        if (self.count >= max_assets or bytes > max_payload_bytes - self.bytes) return error.AssetBudget;
        self.items[self.count] = .{ .kind = kind, .owner = @intCast(owner), .eye = eye, .handle = handle,
            .binding = binding, .memory = memory, .backup_offset = self.bytes };
        self.bytes += @intCast(bytes);
        self.count += 1;
    }

    pub fn resolve(self: *Catalog, raw: *const scanout.Raw, instance: []const u8, framebuffer_bytes: u64) !void {
        self.count = 0;
        self.bytes = 0;
        for (0..scanout.max_heads) |head| {
            if (raw.headMask() & (@as(u8, 1) << @intCast(head)) == 0) continue;
            const color = &raw.heads[head].color;
            const cursor_bytes = try cursorBytes(color.get(.cursor_control));
            if (cursor_bytes != 0) {
                const present = color.get(.cursor_present);
                if (present & ~@as(u32, 1) != 0) return error.AssetControl;
                const eyes: usize = 1 + present;
                for (0..eyes) |eye| try self.add(instance, raw.core_client, 0, .cursor, head, @intCast(eye),
                    color.get(if (eye == 0) .cursor_dma_left else .cursor_dma_right),
                    color.get(if (eye == 0) .cursor_offset_left else .cursor_offset_right), cursor_bytes, framebuffer_bytes);
            }
            if (color.get(.olut_dma) != 0) try self.add(instance, raw.core_client, 0, .olut, head, 0,
                color.get(.olut_dma), color.get(.olut_offset), try lutBytes(.olut, color.get(.olut_control)), framebuffer_bytes);
        }
        for (0..scanout.max_windows) |window| {
            if (raw.window_mask & (@as(u32, 1) << @intCast(window)) == 0 or try scanout.windowHead(&raw.windows[window]) == null) continue;
            const color = &raw.windows[window].color;
            if (color.get(.ilut_dma) != 0) try self.add(instance, raw.windows[window].client, @intCast(1 + window), .ilut, window, 0,
                color.get(.ilut_dma), color.get(.ilut_offset), try lutBytes(.ilut, color.get(.ilut_control)), framebuffer_bytes);
            if (color.get(.tmo_dma) != 0) try self.add(instance, raw.windows[window].client, @intCast(1 + window), .tmo, window, 0,
                color.get(.tmo_dma), color.get(.tmo_offset), try lutBytes(.tmo, color.get(.tmo_control)), framebuffer_bytes);
        }
    }
};
