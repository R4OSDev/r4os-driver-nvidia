pub const Window = struct {
    words: [window_methods.len]u32 = @splat(0),
    pub fn get(self: *const @This(), field: WindowField) u32 {
        return self.words[@intFromEnum(field)];
    }
    /// Enabled indexed LUTs need a separate complete readback/restore path.
    pub fn indexedLuts(self: *const Window) u2 {
        return @as(u2, @intFromBool(self.get(.csc0lut_control) & 16 != 0)) |
            (@as(u2, @intFromBool(self.get(.csc1lut_control) & 16 != 0)) << 1);
    }
};
