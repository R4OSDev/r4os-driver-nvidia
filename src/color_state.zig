pub const Head = struct {
    words: [head_methods.len]u32 = @splat(0),
    cursor_points: [cursor_methods.len]u32 = @splat(0),
    pub fn get(self: *const @This(), field: HeadField) u32 {
        return self.words[@intFromEnum(field)];
    }
    pub fn cursorEnabled(self: *const Head) bool {
        return self.get(.cursor_control) & 0x80000000 != 0;
    }
    pub fn cursorPoint(self: *const Head, eye: u1) Point {
        const raw = self.cursor_points[eye];
        return .{ .x = @bitCast(@as(u16, @truncate(raw))), .y = @bitCast(@as(u16, @truncate(raw >> 16))) };
    }
};
