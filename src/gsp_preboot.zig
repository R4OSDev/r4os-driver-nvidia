//! Fixed570.144 asynchronous boot inputs. These bytes are published into the
//! fresh CPU command queue before exposing its DMA addresses to firmware.
//! Encoding alone neither starts GSP nor creates RM objects or restores video.
const std = @import("std");
const identity = @import("identity.zig");
const firmware = @import("firmware.zig");
pub const system_bytes = 928;
pub const registry_bytes = 8 + 3 * 16 + "RMSecBusResetEnable".len + 1 +
    "RMForcePcieConfigSave".len + 1 + "RMDevidCheckIgnore".len + 1;
pub const config_mirror_base = 0x88000;
pub const config_mirror_bytes = 0x1000;
// R4OS uses four-level x86_64 paging. RM's osGetCpuVaAddrShift adds the
// sign bit to this positive canonical end, yielding48. This is a VA-width
// fact, not a separate user/app mapping or permission boundary in R4OS.
pub const positive_cpu_va_end: u64 = 0x0000_8000_0000_0000;
pub const Error = error{ Profile, Resource, Size, Output };
pub const Payloads = struct {
    system: [system_bytes]u8 = @splat(0),
    registry: [registry_bytes]u8 = @splat(0),
};
comptime {
    if (!std.mem.eql(u8, firmware.lock.rm_version, "570.144") or
        !std.mem.eql(u8, firmware.lock.source_commit, "8ec351aeb96a93a4bb69ccc12a542bf8a8df2b6f"))
        @compileError("GSP preboot inputs require a new original C ABI comparison");
}
fn put32(bytes: []u8, offset: usize, value: u32) void {
    std.mem.writeInt(u32, bytes[offset..][0..4], value, .little);
}
fn put64(bytes: []u8, offset: usize, value: u64) void {
    std.mem.writeInt(u64, bytes[offset..][0..8], value, .little);
}
fn memoryBar(bar: identity.Bar) bool {
    return (bar.kind == .memory32 or bar.kind == .memory64) and bar.base != 0 and bar.base & 4095 == 0;
}
pub fn encode(snapshot: *const identity.Snapshot, console_bytes: u64, out: *Payloads) Error!void {
    // Existing GA106 boot capture uses the same BAR0/BAR1/BAR2 PCI layout.
    // Never treat an upper BAR dword as an independent GPU aperture.
    if (!identity.isDisplay(snapshot.pci) or snapshot.pci.device > 31 or snapshot.pci.function > 7) return error.Profile;
    if (!memoryBar(snapshot.bars[0]) or snapshot.bars[0].kind != .memory32 or
        snapshot.bars[0].bytes < config_mirror_base + config_mirror_bytes or
        !memoryBar(snapshot.bars[1]) or snapshot.bars[1].kind != .memory64 or snapshot.bars[2].kind != .upper or
        !memoryBar(snapshot.bars[3]) or snapshot.bars[3].kind != .memory64 or snapshot.bars[4].kind != .upper) return error.Resource;
    if (console_bytes == 0 or console_bytes > 64 * 1024 * 1024) return error.Size;
    if (snapshot.bars[5].kind != .absent and snapshot.bars[5].kind != .io) return error.Resource;
    out.* = .{};
    const bytes = &out.system;
    put64(bytes, 0, snapshot.bars[0].base);
    put64(bytes, 8, snapshot.bars[1].base);
    put64(bytes, 16, snapshot.bars[3].base);
    if (snapshot.bars[5].kind == .io) put64(bytes, 24, snapshot.bars[5].base);
    // The current canonical PCI API exposes domain0 only.
    put64(bytes, 32, @as(u64, snapshot.pci.bus) << 8 | @as(u64, snapshot.pci.device) << 3 | snapshot.pci.function);
    // Match RM's UEFI console reservation granularity, not its CPU address.
    put64(bytes, 64, std.mem.alignForward(u64, console_bytes, 0x10000));
    put64(bytes, 72, positive_cpu_va_end);
    put32(bytes, 80, config_mirror_base);
    put32(bytes, 84, config_mirror_bytes);
    put32(bytes, 88, @as(u32, snapshot.pci.device_id) << 16 | snapshot.pci.vendor_id);
    put32(bytes, 92, @as(u32, snapshot.subsystem_device) << 16 | snapshot.subsystem_vendor);
    put32(bytes, 96, snapshot.revision);
    bytes[896] = 1; // Caller holds the actual boot-display owner for this GPU.
    put64(bytes, 920, 4096);
    // Unimplemented host services are not advertised: no ACPI method cache,
    // VF/atomics/passthrough, host display-IRQ routing, TDR events or reclock.
    // Firmware retains its normal thermal/performance policy.
    const registry = &out.registry;
    put32(registry, 0, registry.len);
    put32(registry, 4, 3);
    var offset: usize = 8 + 3 * 16;
    inline for (.{ "RMSecBusResetEnable", "RMForcePcieConfigSave", "RMDevidCheckIgnore" }, 0..) |name, index| {
        const entry = 8 + index * 16;
        put32(registry, entry, @intCast(offset));
        registry[entry + 4] = 1; // REGISTRY_TABLE_ENTRY_TYPE_DWORD.
        put32(registry, entry + 8, 1);
        put32(registry, entry + 12, 4);
        @memcpy(registry[offset..][0..name.len], name);
        offset += name.len + 1;
    }
    std.debug.assert(offset == registry.len);
}
