//! GA106 display instance and ISO surface decoding from retained CPU copies.
//! Original NVIDIA definitions/algorithms: pinned GA102 display manual and
//! RM/NVKMS 570.144. Full notices are inserted above this module documentation.
//! This decoder grants no native display execution or recovery authority.
const std = @import("std");
pub const instance_control_register: u32 = 0x610010;
pub const instance_address_register: u32 = 0x610014;
pub const client_register: u32 = 0x610b2c;
pub const instance_bytes = 65536;
pub const hash_bytes = 8192;
pub const entries = hash_bytes / 8;
pub const descriptor_bytes = 20;
pub const Error = error{ Control, Target, Bounds, Reserved, Missing, Duplicate, Format, Plane, Stereo, Geometry, Pitch, Context, Capacity };
pub const Span = struct { address: u64, bytes: u64 };
pub fn instance(control: u32, address: u32, framebuffer_bytes: u64) Error!Span {
    if (control & ~@as(u32, 11) != 0 or control & 8 == 0 or address & 0x80000000 != 0) return error.Control;
    if (control & 3 != 1) return error.Target;
    const base = @as(u64, address) << 16;
    if (base > framebuffer_bytes or instance_bytes > framebuffer_bytes - base) return error.Bounds;
    return .{ .address = base, .bytes = instance_bytes };
}
pub fn hash(client: u14, handle: u32, channel: u7) u10 {
    const c = @as(u32, client);
    const ch = @as(u32, channel);
    return @intCast((handle & 0x3ff) ^ ((handle >> 10) & 0x3ff) ^ ((handle >> 20) & 0x3ff) ^
        (((c & 0xff) << 2) | (handle >> 30)) ^ (((ch & 15) << 6) | ((c >> 8) & 63)) ^ ((ch >> 4) & 7));
}
fn word(data: []const u8, offset: usize) u32 {
    return std.mem.readInt(u32, data[offset..][0..4], .little);
}
pub const Target = enum(u2) { vram = 1, pci = 2, pci_coherent = 3 };
pub const Layout = enum { pitch, block_linear };
pub const Descriptor = struct { address: u64, end: u64, target: Target, layout: Layout, writable: bool, small_page: bool };
pub const Resolved = struct { entry: u16, offset: u16, descriptor: Descriptor };
pub fn decode(data: []const u8) Error!Descriptor {
    if (data.len != descriptor_bytes) return error.Bounds;
    const flags = word(data, 0);
    if (flags & ~@as(u32, 0x100047) != 0 or word(data, 8) & ~@as(u32, 127) != 0 or
        word(data, 16) & ~@as(u32, 127) != 0) return error.Reserved;
    const target = std.enums.fromInt(Target, flags & 3) orelse return error.Target;
    const base = (@as(u64, word(data, 4)) | (@as(u64, word(data, 8)) << 32)) << 8;
    // The programmed inclusive limit drops eight address bits. Restore the
    // complete final 256-byte unit, expressed here as an exclusive bound.
    const end = ((@as(u64, word(data, 12)) | (@as(u64, word(data, 16)) << 32)) + 1) << 8;
    if (end <= base) return error.Bounds;
    return .{ .address = base, .end = end, .target = target, .layout = if (flags & 0x100000 != 0) .block_linear else .pitch, .writable = flags & 4 != 0, .small_page = flags & 64 != 0 };
}
pub fn lookup(data: []const u8, client: u14, handle: u32, channel: u7) Error!Resolved {
    if (data.len != instance_bytes or handle == 0) return error.Context;
    var found: ?Resolved = null;
    const start: usize = hash(client, handle, channel);
    for (0..entries) |step| {
        const slot = (start + step) & (entries - 1);
        const ctx = word(data, slot * 8 + 4);
        const object = (ctx >> 14) & 0x7ff;
        if (object == 0 or word(data, slot * 8) != handle or ctx & 0x3fff != client or ctx >> 25 != channel) continue;
        if (found != null) return error.Duplicate;
        const offset = object << 5;
        if (offset < hash_bytes or offset > instance_bytes - descriptor_bytes) return error.Bounds;
        found = .{ .entry = @intCast(slot), .offset = @intCast(offset), .descriptor = try decode(data[offset..][0..descriptor_bytes]) };
    }
    return found orelse error.Missing;
}
const PlaneFormat = struct { bytes: u8, x: u8 = 1, y: u8 = 1 };
pub const Format = struct { count: u2, planes: [3]PlaneFormat };
fn rgb(bytes: u8) Format {
    return .{ .count = 1, .planes = .{ .{ .bytes = bytes }, .{ .bytes = 0 }, .{ .bytes = 0 } } };
}
fn yuv(count: u2, bytes: u8, x: u8, y: u8) Format {
    return .{ .count = count, .planes = .{ .{ .bytes = bytes }, .{ .bytes = if (count == 2) bytes * 2 else bytes, .x = x, .y = y }, .{ .bytes = bytes, .x = x, .y = y } } };
}
/// C67E codes only. Unknown formats cannot authorize a guessed buffer extent.
pub fn format(code: u8) Error!Format {
    return switch (code) {
        0x1e => rgb(1),
        0x2f, 0xe8, 0xe9, 0x2e => rgb(2),
        0xcf, 0xe6, 0xd5, 0xf9, 0xdf, 0xd1 => rgb(4),
        0x23, 0xc6, 0xca => rgb(8),
        0x28, 0x29 => rgb(2), // Packed YUV 4:2:2, one plane/two bytes per pixel.
        0x35 => yuv(2, 1, 1, 1),
        0x36 => yuv(2, 1, 2, 1),
        0x38 => yuv(2, 1, 2, 2),
        0x3a => yuv(3, 1, 1, 1),
        0x3b => yuv(3, 1, 2, 2),
        0x55, 0x75 => yuv(2, 2, 1, 1),
        0x56, 0x76 => yuv(2, 2, 2, 1),
        0x58, 0x78 => yuv(2, 2, 2, 2),
        else => error.Format,
    };
}
pub fn eyes(present: u32) Error!u2 {
    return switch ((present >> 12) & 3) {
        0 => 1,
        1, 2 => 2,
        else => error.Stereo,
    };
}
pub const Surface = struct { span: Span, row_bytes: u64, rows: u64, layout: Layout };
pub fn surface(desc: Descriptor, offset: u64, width: u16, height: u16, encoded_pitch: u32, storage: u32, pixel_format: Format, plane: u2, framebuffer_bytes: u64) Error!Surface {
    if (desc.target != .vram) return error.Target;
    if (plane >= pixel_format.count or plane >= 3) return error.Plane;
    if (width == 0 or height == 0) return error.Geometry;
    if (encoded_pitch & ~@as(u32, 8191) != 0 or encoded_pitch == 0) return error.Pitch;
    if (storage & ~@as(u32, 15) != 0) return error.Reserved;
    const sample = pixel_format.planes[plane];
    const required_row = (@as(u64, width) * sample.bytes + sample.x - 1) / sample.x;
    const row_bytes = @as(u64, encoded_pitch) * 64;
    if (required_row > row_bytes) return error.Pitch;
    // NVKMS rounds odd chroma widths up and forces decimated heights even
    // before division. The whole surface extent is protected, not just a crop.
    var rows: u64 = if (sample.y == 2) (height & ~@as(u16, 1)) / 2 else height;
    if (rows == 0) return error.Geometry;
    if (desc.layout == .block_linear) {
        if (storage > 5) return error.Reserved;
        const block_rows = @as(u64, 8) << @intCast(storage);
        rows = (rows + block_rows - 1) & ~(block_rows - 1);
    }
    const bytes = row_bytes * rows;
    if (offset & 255 != 0 or desc.address > desc.end or offset > desc.end - desc.address or
        bytes > desc.end - desc.address - offset) return error.Bounds;
    const address = desc.address + offset;
    if (address > framebuffer_bytes or bytes > framebuffer_bytes - address) return error.Bounds;
    return .{ .span = .{ .address = address, .bytes = bytes }, .row_bytes = row_bytes, .rows = rows, .layout = desc.layout };
}
