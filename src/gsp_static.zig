//! Pinned570.144 GET_GSP_STATIC_INFO payload. Decode before ACK and retain
//! only bounded values; these observations do not grant VRAM allocation or
//! permission to dereference firmware addresses. Internal handles belong to
//! firmware and must never be freed through the host-created RM object graph.
const std = @import("std");
const message = @import("gsp_message.zig");
const firmware = @import("firmware.zig");
pub const function: u32 = 65;
pub const payload_bytes = 1656;
pub const max_regions = 16;
pub const Error = error{ Unexpected, Guest, Rpc, Payload, Handle, Memory, Region };
pub const Region = struct {
    base: u64 = 0,
    bytes: u64 = 0,
    reserved: u64 = 0,
    performance: u32 = 0,
    compressed: bool = false,
    iso: bool = false,
    protected: bool = false,
};
pub const Info = struct {
    client: u32,
    device: u32,
    subdevice: u32,
    fb_bytes: u64,
    bar1_pdb: u64,
    bar2_pdb: u64,
    engine_caps: [3]u32,
    region_count: usize,
    regions: [max_regions]Region = @splat(.{}),
    // Diagnostic firmware layout values; GA106 keeps its original pinned
    // boot reservation. This query never silently replaces that reservation.
    non_wpr_heap: u64,
    frts: u64,
};
comptime {
    if (!std.mem.eql(u8, firmware.lock.rm_version, "570.144") or
        !std.mem.eql(u8, firmware.lock.source_commit, "8ec351aeb96a93a4bb69ccc12a542bf8a8df2b6f"))
        @compileError("GSP static data requires a new original-source ABI comparison");
}
fn get(comptime T: type, bytes: []const u8, offset: usize) T {
    return std.mem.readInt(T, bytes[offset..][0..@sizeOf(T)], .little);
}
fn flag(bytes: []const u8, offset: usize) Error!bool {
    if (bytes[offset] > 1) return error.Payload;
    return bytes[offset] == 1;
}
/// The sole Exchange correlates the reply by its outstanding function.
/// RPC sequence/private are diagnostics, not an assumed echoed request ID.
pub fn decode(record: message.Record, physical_bytes: u64) Error!Info {
    if (record.rpc.function != function) return error.Unexpected;
    if (record.rpc.cpu_rm_gfid != 0) return error.Guest;
    if (record.rpc.result == message.pending) return error.Payload;
    if (record.rpc.result != 0) return error.Rpc;
    const bytes = record.payload;
    if (bytes.len != payload_bytes) return error.Payload;
    var info: Info = .{
        .client = get(u32, bytes, 1600), .device = get(u32, bytes, 1604),
        .subdevice = get(u32, bytes, 1608), .fb_bytes = get(u64, bytes, 1224),
        .bar1_pdb = get(u64, bytes, 1536), .bar2_pdb = get(u64, bytes, 1544),
        .engine_caps = .{ get(u32, bytes, 1204), get(u32, bytes, 1208), get(u32, bytes, 1212) },
        .region_count = get(u32, bytes, 344),
        .non_wpr_heap = get(u64, bytes, 1640), .frts = get(u64, bytes, 1648),
    };
    if (info.client == 0 or info.device == 0 or info.subdevice == 0 or info.device == info.subdevice) return error.Handle;
    if (physical_bytes == 0 or info.fb_bytes == 0 or info.fb_bytes > physical_bytes) return error.Memory;
    for ([_]u64{ info.bar1_pdb, info.bar2_pdb }) |base|
        if (base & 7 != 0 or base >= physical_bytes) return error.Memory;
    if (info.region_count == 0 or info.region_count > max_regions) return error.Region;
    for (info.regions[0..info.region_count], 0..) |*region, index| {
        const at = 352 + index * 48;
        const base = get(u64, bytes, at);
        const limit = get(u64, bytes, at + 8);
        const reserved = get(u64, bytes, at + 16);
        if (base > limit or limit >= physical_bytes or reserved > limit - base + 1) return error.Region;
        for (info.regions[0..index]) |earlier|
            if (base < earlier.base + earlier.bytes and earlier.base <= limit) return error.Region;
        region.* = .{ .base = base, .bytes = limit - base + 1, .reserved = reserved,
            .performance = get(u32, bytes, at + 24), .compressed = try flag(bytes, at + 28),
            .iso = try flag(bytes, at + 29), .protected = try flag(bytes, at + 30) };
    }
    return info;
}
