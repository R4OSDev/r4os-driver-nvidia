//! RM mode feasibility for one progressive RGB8, unscaled pitch surface.
//! Query results are observations, never a reservation, modeset or proof of
//! display quiescence. The Device worker owns the real Exchange throughout.
const std = @import("std");
const boot = @import("gsp_boot_events.zig");
const exchange = @import("gsp_exchange.zig");
const names = @import("gsp_rm_names.zig");
const modes = @import("gsp_boot_mode.zig");
const root_wire = @import("gsp_display_engine_wire.zig");
pub const Error = exchange.Error || names.Error || modes.Error;
pub const Operation = enum { classes, allocate, pclk, possible, free };
pub const State = enum { querying, unwinding, ready, handed_off, destroying, closed, finished, failed };
pub const max_bytes = 2072;
pub const control_class: u32 = 0xc372;
pub const Binding = struct { epoch: u64, client: u32, device: u32, display: u32, control: u32 };
pub const Result = struct {
    mode: modes.Plan,
    source_clock_hz: u64,
    possible: bool,
    over_clock: bool,
    min_bandwidth_kbps: u32 = 0,
    floor_bandwidth_kbps: u32 = 0,
    min_hubclock_khz: u32 = 0,
    display_clock_khz: u32 = 0,
    receipt: u64,
};
pub fn function(op: Operation) u32 { return switch (op) { .allocate => 103, .free => 10, else => 76 }; }
pub fn length(op: Operation) usize { return switch (op) { .classes => 428, .allocate => 32, .pclk => 44, .possible => max_bytes, .free => 16 }; }
pub fn word(data: []const u8, at: usize) u32 { return std.mem.readInt(u32, data[at..][0..4], .little); }
fn put(data: []u8, at: usize, value: u32) void { std.mem.writeInt(u32, data[at..][0..4], value, .little); }
fn validate(binding: Binding, mode: modes.Plan) Error!void {
    if (binding.epoch == 0 or mode.epoch != binding.epoch or mode.held_generation == 0 or mode.boot_generation == 0 or
        mode.output_generation == 0 or mode.receipt_serial == 0) return error.Stale;
    const handles = [_]u32{ binding.client, binding.device, binding.display, binding.control };
    for (handles, 0..) |handle, i| {
        if (handle == 0) return error.Handle;
        for (handles[0..i]) |prior| if (handle == prior) return error.Handle;
    }
    try modes.validate(mode.signal, mode.head);
    if (mode.window >= 8 or mode.width != mode.signal.viewport & 0xffff or mode.height != mode.signal.viewport >> 16) return error.Descriptor;
}
pub fn encode(binding: Binding, op: Operation, mode: modes.Plan, buffer: []u8) Error![]const u8 {
    try validate(binding, mode);
    if (buffer.len < length(op)) return error.Bounds;
    const out = buffer[0..length(op)]; @memset(out, 0); put(out, 0, binding.client);
    switch (op) {
        .allocate => { put(out, 4, binding.device); put(out, 8, binding.control); put(out, 12, control_class); },
        .free => put(out, 8, binding.control),
        else => {
            put(out, 4, switch (op) { .classes => binding.device, .pclk => binding.display, else => binding.control });
            put(out, 8, switch (op) { .classes => 0x800292, .pclk => 0x73028a, else => 0xc3720101 });
            put(out, 16, @intCast(out.len - 24));
            if (op == .pclk) put(out, 28, mode.signal.display_id);
            if (op == .possible) {
                const data = out[24..];
                data[4] = 1; data[5] = 1; // Dense arrays: one head, one window.
                const head = data[8..][0..92];
                head[0] = @intCast(mode.head);
                // IMP accepts integer kHz, so round the nominal clock upward.
                // Keeping the unadjusted rate is conservative for 1000/1001.
                put(head, 4, @intCast((@as(u64, mode.signal.clock & 0x7fffffff) + 999) / 1000));
                const raster = [_]u32{ mode.signal.total, mode.signal.blank_start, mode.signal.blank_end };
                for (raster, 0..) |pair, i| { put(head, 8 + i * 8, pair & 0xffff); put(head, 12 + i * 8, pair >> 16); }
                put(head, 44, 16); put(head, 52, 16); // NO_LOCK, PIN_UNSPECIFIED.
                put(head, 56, 1024); put(head, 60, 1024); head[64] = 1;
                put(head, 68, mode.signal.min_frame_idle);
                // Cursor, LUTs, rotation, scaling, DSC, overfetch and YUV stay off.
                const window = data[744..][0..36];
                put(window, 0, mode.window); put(window, 4, mode.head); put(window, 8, 4);
                put(window, 16, mode.width); put(window, 20, 1024); put(window, 24, 1024);
                window[28] = 1; window[33] = 1; // One tap, PITCH layout.
                put(data, 1896, 3); // Fresh min-vpstate and margin query; no cached perf.
            }
        },
    }
    return out;
}
pub const Reply = union(enum) { rejected: u32, ok: []const u8 };
pub fn decode(binding: Binding, op: Operation, mode: modes.Plan, request: []const u8, record: exchange.message.Record) Error!Reply {
    try validate(binding, mode);
    if (request.len != length(op) or record.rpc.function != function(op) or record.rpc.cpu_rm_gfid != 0) return error.Payload;
    if (record.rpc.result != 0) return error.FirmwareResult;
    const header: usize = if (op == .allocate) 32 else if (op == .free) 16 else 24;
    const status_at: usize = if (op == .allocate) 16 else 12;
    const data = record.payload;
    if (data.len != header and data.len != request.len) return error.Payload;
    for (data[0..header], 0..) |value, i| {
        if (i >= status_at and i < status_at + 4) continue;
        if (value != request[i]) return error.Unexpected;
    }
    if (word(data, status_at) != 0) return .{ .rejected = word(data, status_at) };
    if (data.len != request.len) return error.Payload;
    const payload = data[header..];
    switch (op) {
        .classes => if (word(payload, 0) > 100) return error.Bounds,
        .pclk => if (!std.mem.eql(u8, payload[0..8], request[24..32]) or word(payload, 12) == 0) return error.Payload,
        .possible => {
            if (!std.mem.eql(u8, payload[0..1904], request[24..1928]) or
                !std.mem.eql(u8, payload[2044..], request[2068..]) or payload[1904] > 1 or
                !std.mem.allEqual(u8, payload[1913..1916], 0) or word(payload, 2008) > 8) return error.Payload;
            for (payload[1905..1913]) |flag| if (flag > 1) return error.Payload;
        },
        .allocate, .free => {},
    }
    return .{ .ok = payload };
}
pub const Owner = struct {
    self_address: usize = 0,
    exchange: exchange.Exchange,
    binding: Binding,
    reservation: names.Children,
    mode: modes.Plan,
    state: State = .querying,
    namespace_live: bool = true,
    classes: bool = false,
    live: bool = false,
    allocation_possible: bool = false,
    unavailable: bool = false,
    source_clock_hz: u64 = 0,
    result: ?Result = null,
    rejected: ?u32 = null,
    last_status: ?u32 = null,
    failure: ?Error = null,
    protocol_failure: ?exchange.Error = null,
    operation: ?Operation = null,
    request: [max_bytes]u8 = undefined,
    deadline: u64,
    pub fn init(token: *boot.Handoff, parent: names.Lease, device: u32, display: u32, mode: modes.Plan, deadline: u64) Error!Owner {
        if (token.claimed or token.session.state != .active or token.session.pending != null or parent.epoch != token.session.epoch) return error.Stale;
        try token.session.guard(deadline);
        const children = try token.session.rm_names.reserveChildren(parent, 1);
        errdefer token.session.rm_names.retireChildren(children) catch {};
        const binding: Binding = .{ .epoch = parent.epoch, .client = parent.client, .device = device, .display = display, .control = try children.object(0) };
        try validate(binding, mode);
        return .{ .exchange = try exchange.Exchange.init(token, deadline), .binding = binding, .reservation = children, .mode = mode, .deadline = deadline };
    }
    fn stable(self: *const Owner) Error!void {
        if ((self.self_address != 0 and self.self_address != @intFromPtr(self)) or self.binding.epoch != self.exchange.session.epoch) return error.Stale;
        if (self.namespace_live) try self.exchange.session.rm_names.validateChildren(self.reservation);
    }
    pub fn info(self: *const Owner) ?Result {
        self.stable() catch return null;
        if (self.self_address != @intFromPtr(self) or !self.live or self.exchange.session.state != .active or
            (self.state != .ready and self.state != .handed_off)) return null;
        return self.result;
    }
    pub fn poll(self: *Owner) Error!?exchange.Dispatch {
        try self.stable();
        if (self.state != .querying and self.state != .unwinding and self.state != .destroying) return error.State;
        self.self_address = @intFromPtr(self);
        return self.advance() catch |err| {
            if (err == error.Pending) return err;
            self.failure = err; self.state = .failed;
            if (self.namespace_live) self.exchange.session.rm_names.retainChildren(self.reservation) catch {};
            self.protocol_failure = self.exchange.fail(error.Handler); return err;
        };
    }
    fn advance(self: *Owner) Error!?exchange.Dispatch {
        try self.exchange.guard(self.deadline);
        if (self.exchange.pending != null) return error.Pending;
        if (self.operation == null) {
            const op: Operation = if (self.state == .querying) blk: {
                if (!self.classes) break :blk .classes;
                if (!self.live) break :blk .allocate;
                if (self.source_clock_hz == 0) break :blk .pclk;
                if (self.result == null) break :blk .possible;
                self.state = .ready; return null;
            } else if (self.live) .free else {
                if (self.namespace_live) { try self.exchange.session.rm_names.retireChildren(self.reservation); self.namespace_live = false; }
                self.state = if (self.state == .unwinding) .ready else .closed; return null;
            };
            const data = try encode(self.binding, op, self.mode, &self.request);
            try self.exchange.begin(function(op), data, self.deadline); self.operation = op;
            if (op == .allocate) self.allocation_possible = true;
        }
        const dispatch = (try self.exchange.poll(self.deadline)) orelse return null;
        if (!dispatch.response) return dispatch;
        const op = self.operation.?;
        const reply = try decode(self.binding, op, self.mode, self.request[0..length(op)], dispatch.record);
        self.last_status = if (reply == .rejected) reply.rejected else 0;
        try self.exchange.complete(dispatch.ticket);
        if (reply == .rejected) {
            if (op == .free) return error.FirmwareResult;
            if (op == .allocate) self.allocation_possible = false;
            self.rejected = reply.rejected; self.state = .unwinding;
        } else switch (op) {
            .classes => if (root_wire.supportsClass(reply.ok, control_class)) { self.classes = true; }
                else { self.unavailable = true; self.state = .unwinding; },
            .allocate => self.live = true,
            .pclk => {
                // Non-SLI uses the OR limit, not min(OR, video-bridge limit).
                self.source_clock_hz = @as(u64, word(reply.ok, 12)) * 1000;
                const nominal: u128 = self.mode.signal.clock & 0x7fffffff;
                const adjusted = self.mode.signal.clock >> 31 != 0;
                if (nominal * @as(u128, if (adjusted) 1000 else 1) > self.source_clock_hz * @as(u128, if (adjusted) 1001 else 1))
                    self.result = .{ .mode = self.mode, .source_clock_hz = self.source_clock_hz, .possible = false, .over_clock = true, .receipt = dispatch.ticket.serial };
            },
            .possible => self.result = .{ .mode = self.mode, .source_clock_hz = self.source_clock_hz,
                .possible = reply.ok[1904] != 0, .over_clock = false,
                .min_bandwidth_kbps = word(reply.ok, 1924), .floor_bandwidth_kbps = word(reply.ok, 1928),
                .min_hubclock_khz = word(reply.ok, 1932), .display_clock_khz = word(reply.ok, 2004), .receipt = dispatch.ticket.serial },
            .free => { self.live = false; self.allocation_possible = false; self.result = null; },
        }
        self.operation = null; return null;
    }
    pub fn beginQuery(self: *Owner, token: *boot.Handoff, mode: modes.Plan, deadline: u64) Error!void {
        try self.stable(); try validate(self.binding, mode);
        if (self.state != .handed_off or !self.live or token.session != self.exchange.session) return error.State;
        self.exchange = try exchange.Exchange.init(token, deadline); self.deadline = deadline;
        self.mode = mode; self.source_clock_hz = 0; self.result = null; self.rejected = null; self.state = .querying;
    }
    pub fn beginDestroy(self: *Owner, token: *boot.Handoff, deadline: u64) Error!void {
        try self.stable();
        if (self.state != .handed_off or token.session != self.exchange.session) return error.State;
        self.exchange = try exchange.Exchange.init(token, deadline); self.deadline = deadline; self.state = .destroying;
    }
    pub fn handoff(self: *Owner) Error!boot.Handoff {
        try self.stable();
        if (self.state != .ready and self.state != .closed) return error.State;
        const token = try self.exchange.handoff(self.deadline);
        self.state = if (self.state == .closed) .finished else .handed_off; return token;
    }
    pub fn matches(self: *const Owner, current: *const exchange.Exchange, deadline: u64) bool {
        self.stable() catch return false;
        const op = self.operation orelse return false;
        var expected: [max_bytes]u8 = undefined;
        const encoded = encode(self.binding, op, self.mode, &expected) catch return false;
        return self.self_address == @intFromPtr(self) and current == &self.exchange and current.deadline == deadline and self.deadline == deadline and
            current.request.ptr == self.request[0..].ptr and current.request.len == length(op) and current.function == function(op) and
            std.mem.eql(u8, current.request, encoded) and (self.state == .querying or self.state == .unwinding or self.state == .destroying);
    }
};
