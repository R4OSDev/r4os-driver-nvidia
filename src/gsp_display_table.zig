//! GA106 display RAMHT and GV100-format physical DMA contexts. References
//! belong to the enclosing display owner; publication requires a completed
//! GPU transfer of this exact revision. Pinned sources and full notices above.
const std = @import("std");
pub const Error = error{Bounds, Handle, Busy, Stale, Exhausted, Unsupported};
pub const capacity: usize = 64;
pub const ramht_bytes: usize = 8192;
pub const descriptor_bytes: usize = 32; // 24-byte descriptor, aligned to32.
pub const image_bytes: usize = ramht_bytes + capacity * descriptor_bytes;
pub const Target = enum { vram, coherent_system };
pub const Descriptor = struct { channel: u32, handle: u32, target: Target, physical: u64, bytes: u64 };
pub const Change = struct { index: u8, bucket: u16, remove: bool };
pub const Range = struct { offset: u32, bytes: u32 };
pub const Table = struct {
    self_address: usize = 0,
    client: u32 = 0,
    root: u32 = 0,
    epoch: u64 = 0,
    image: [image_bytes]u8 = @splat(0),
    entries: [capacity]?Descriptor = @splat(null),
    buckets: [ramht_bytes / 8]?u8 = @splat(null),
    entry_revisions: [capacity]u64 = @splat(0),
    change: ?Change = null,
    count: u32 = 0,
    revision: u64 = 0,
    uploaded_revision: u64 = 0,
    uploading: bool = false,
    digest: u64 = 0,
    failed: bool = false,

    pub fn init(self: *Table, client: u32, root: u32, epoch: u64) Error!void {
        if (self.self_address != 0) return error.Busy;
        if (client == 0 or root == 0 or root == client or epoch == 0) return error.Handle;
        self.* = .{ .self_address = @intFromPtr(self), .client = client, .root = root, .epoch = epoch };
    }
    pub fn valid(self: *const Table) bool {
        return self.self_address == @intFromPtr(self) and !self.failed and self.epoch != 0 and self.client != 0 and self.root != 0 and
            self.count <= capacity and self.uploaded_revision <= self.revision;
    }
    pub fn add(self: *Table, input: Descriptor) Error!void {
        if (!self.valid()) return error.Stale;
        if (self.uploading or self.change != null) return error.Busy;
        try validate(input);
        if (input.handle == self.root or input.handle == self.client) return error.Handle;
        if (self.count >= capacity or self.revision == std.math.maxInt(u64)) return error.Exhausted;
        for (&self.entries) |item| if (item) |entry| if (entry.handle == input.handle) return error.Handle;
        const index = self.freeIndex() orelse return error.Exhausted;
        var bucket = hash(input.channel, input.handle);
        var probed: usize = 0;
        while (self.buckets[bucket] != null and probed < self.buckets.len) : (probed += 1) bucket = (bucket + 1) % self.buckets.len;
        if (probed == self.buckets.len) return error.Exhausted;
        const offset: u32 = @intCast(ramht_bytes + index * descriptor_bytes);
        const words = descriptor(input);
        for (words, 0..) |word, i| put(&self.image, offset + i * 4, word);
        put(&self.image, bucket * 8, input.handle);
        put(&self.image, bucket * 8 + 4, (input.channel << 25) | (offset << 9) | (self.client & 0x3fff));
        self.entries[index] = input; self.buckets[bucket] = @intCast(index);
        self.count += 1; self.revision += 1;
        self.entry_revisions[index] = self.revision;
        if (self.uploaded_revision != 0) self.change = .{ .index = @intCast(index), .bucket = @intCast(bucket), .remove = false };
    }
    pub fn freeIndex(self: *const Table) ?usize {
        for (&self.entries, 0..) |entry, i| if (entry == null) return i;
        return null;
    }
    pub fn indexOf(self: *const Table, channel: u32, handle: u32) ?usize {
        for (&self.entries, 0..) |entry, i| if (entry) |value| {
            if (value.channel == channel and value.handle == handle) return i;
        };
        return null;
    }
    /// The runtime must already have proved this image is no longer selected
    /// by any completed or pending display operation. Keep its storage and
    /// descriptor until the exact RAMHT withdrawal has completed on the CE.
    pub fn remove(self: *Table, channel: u32, handle: u32) Error!void {
        if (!self.valid()) return error.Stale;
        if (self.uploading or self.change != null or self.revision != self.uploaded_revision) return error.Busy;
        const index = self.indexOf(channel, handle) orelse return error.Handle;
        if (self.revision == std.math.maxInt(u64)) return error.Exhausted;
        for (&self.buckets, 0..) |item, bucket| if (item != null and item.? == index) {
            put(&self.image, bucket * 8, 0); put(&self.image, bucket * 8 + 4, 0);
            self.revision += 1;
            self.change = .{ .index = @intCast(index), .bucket = @intCast(bucket), .remove = true };
            return;
        };
        return error.Stale;
    }
    pub fn finishRemove(self: *Table) Error!usize {
        if (!self.valid() or self.uploading or self.uploaded_revision != self.revision) return error.Stale;
        const change = self.change orelse return error.Stale;
        if (!change.remove) return error.Stale;
        self.entries[change.index] = null; self.entry_revisions[change.index] = 0;
        self.buckets[change.bucket] = null; self.count -= 1;
        @memset(self.image[ramht_bytes + @as(usize, change.index) * descriptor_bytes..][0..descriptor_bytes], 0);
        self.change = null;
        return change.index;
    }
    /// Live additions write an unused descriptor first, then its new RAMHT
    /// bucket after a SYS-flushed CE completion. No active entry is rewritten.
    /// Removal only clears the retired bucket. The initial upload stays whole.
    pub fn uploadRange(self: *const Table, part: u8) Error!Range {
        if (!self.valid()) return error.Stale;
        if (self.change) |change| {
            if (!change.remove and part == 0) return .{ .offset = @intCast(ramht_bytes + @as(usize, change.index) * descriptor_bytes), .bytes = descriptor_bytes };
            if (part == @as(u8, if (change.remove) 0 else 1)) return .{ .offset = @as(u32, change.bucket) * 8, .bytes = 8 };
            return error.Bounds;
        }
        if (part != 0 or self.uploaded_revision != 0) return error.Bounds;
        return .{ .offset = 0, .bytes = image_bytes };
    }
    pub fn uploadParts(self: *const Table) u8 {
        return if (self.change) |change| if (change.remove) 1 else 2 else 1;
    }
    pub fn beginUpload(self: *Table) Error![]const u8 {
        if (!self.valid()) return error.Stale;
        if (self.uploading or self.count == 0 or self.uploaded_revision == self.revision) return error.Busy;
        self.digest = std.hash.Wyhash.hash(0, &self.image); self.uploading = true;
        return &self.image;
    }
    pub fn uploadingRevision(self: *const Table, revision: u64) bool {
        return self.valid() and self.uploading and self.revision == revision and self.digest == std.hash.Wyhash.hash(0, &self.image);
    }
    pub fn completeUpload(self: *Table, revision: u64) Error!void {
        if (!self.uploadingRevision(revision)) return error.Stale;
        self.uploaded_revision = revision; self.uploading = false;
        if (self.change) |change| if (!change.remove) { self.change = null; };
    }
    /// The enclosing owner must have no submitted transfer left and must
    /// already have dropped its staging read lease. A completed descriptor-only
    /// first part is harmless: the new handle has not yet been published.
    pub fn cancelUpload(self: *Table, revision: u64) Error!void {
        if (!self.uploadingRevision(revision)) return error.Stale;
        self.uploading = false;
    }
    pub fn published(self: *const Table, channel: u32, handle: u32) bool {
        if (!self.valid() or self.uploaded_revision == 0) return false;
        const index = self.indexOf(channel, handle) orelse return false;
        if (self.change) |change| if (change.remove and change.index == index) return false;
        return self.entry_revisions[index] != 0 and self.entry_revisions[index] <= self.uploaded_revision;
    }
};
pub fn validate(input: Descriptor) Error!void {
    if (input.channel > 8 or input.handle == 0) return error.Handle;
    if (input.physical == 0 or input.physical & 255 != 0 or input.bytes == 0 or input.bytes & 255 != 0 or
        input.physical >= @as(u64, 1) << 40 or input.bytes > (@as(u64, 1) << 40) - input.physical) return error.Bounds;
}
pub fn hash(channel: u32, handle: u32) usize {
    var value = handle; var result: u32 = 0;
    while (value != 0) : (value >>= 10) result ^= value & 1023;
    return result ^ (channel << 6);
}
pub fn descriptor(input: Descriptor) [6]u32 {
    const start = input.physical >> 8; const limit = (input.physical + input.bytes - 1) >> 8;
    return .{if (input.target == .vram) 0x45 else 0x46, @truncate(start), @truncate(start >> 32), @truncate(limit), @truncate(limit >> 32), 0};
}
fn put(bytes: []u8, offset: usize, word: u32) void { std.mem.writeInt(u32, bytes[offset..][0..4], word, .little); }
