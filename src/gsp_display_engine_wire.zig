//! Native display-root RM protocol, pinned to NVIDIA 570.144 / GA106.
//! This owns no display DMA channel and publishes no scanout capability.
const std = @import("std");
const exchange = @import("gsp_exchange.zig");
pub const Error = exchange.Error || error{Unsupported};
pub const Operation = enum { classes, static_info, allocate, preserve, free, instance };
pub const max_bytes = 428;
pub const root_class: u32 = 0xc670;
pub const Binding = struct { epoch: u64, client: u32, device: u32, root: u32, internal_client: u32, internal_subdevice: u32 };
pub const StaticInfo = struct {
    capabilities: u32, windows: u32, fb_remapper: bool, heads: u32, i2c_port: u32,
    internal_displays: u32, embedded_dp: u32, external_mux: bool, internal_mux: bool, channels: u32,
};
pub const Reply = union(enum) { rejected: u32, ok: []const u8 };
pub fn function(op: Operation) u32 { return switch (op) { .allocate => 103, .free => 10, else => 76 }; }
pub fn length(op: Operation) usize { return switch (op) { .classes => 428, .static_info => 60, .allocate, .preserve => 32, .free => 16, .instance => 48 }; }
pub fn command(op: Operation) u32 { return switch (op) { .classes => 0x800292, .static_info => 0x20800a01, .preserve => 0x50700117, .instance => 0x20800a49, else => 0 }; }
pub fn word(data: []const u8, at: usize) u32 { return std.mem.readInt(u32, data[at..][0..4], .little); }
fn put(out: []u8, at: usize, value: u32) void { std.mem.writeInt(u32, out[at..][0..4], value, .little); }
pub fn validate(binding: Binding) Error!void {
    if (binding.epoch == 0) return error.Stale;
    if (binding.client == 0 or binding.device == 0 or binding.root == 0 or binding.internal_client == 0 or binding.internal_subdevice == 0 or
        binding.client == binding.device or binding.client == binding.root or binding.device == binding.root or binding.internal_client == binding.client) return error.Handle;
}
pub fn encode(binding: Binding, op: Operation, output: []u8) Error![]const u8 {
    try validate(binding);
    if (output.len < length(op)) return error.Bounds;
    const out = output[0..length(op)]; @memset(out, 0);
    put(out, 0, if (op == .static_info) binding.internal_client else binding.client);
    switch (op) {
        .classes, .static_info, .preserve => {
            put(out, 4, switch (op) { .classes => binding.device, .static_info => binding.internal_subdevice, else => binding.root });
            put(out, 8, command(op)); put(out, 16, @intCast(out.len - 24));
            // subdeviceIndex=0; the one-shot flag applies to the NEXT RmFree.
            if (op == .preserve) put(out, 28, 1);
        },
        .allocate => { put(out, 4, binding.device); put(out, 8, binding.root); put(out, 12, root_class); },
        .free => put(out, 8, binding.root),
        .instance => return error.Unsupported, // Requires retained physical storage.
    }
    return out;
}
pub fn encodeInstance(binding: Binding, physical: u64, output: []u8) Error![]const u8 {
    try validate(binding);
    if (physical == 0 or physical & 0xffff != 0 or physical > std.math.maxInt(u64) - 65536 or output.len < 48) return error.Bounds;
    const out = output[0..48]; @memset(out, 0);
    put(out, 0, binding.internal_client); put(out, 4, binding.internal_subdevice); put(out, 8, command(.instance)); put(out, 16, 24);
    std.mem.writeInt(u64, out[24..32], physical, .little); std.mem.writeInt(u64, out[32..40], 65536, .little);
    put(out, 40, 2); put(out, 44, 2); // ADDR_FBMEM; NV_MEMORY_WRITECOMBINED.
    return out;
}
pub fn decode(binding: Binding, op: Operation, request: []const u8, record: exchange.message.Record) Error!Reply {
    try validate(binding);
    if (request.len != length(op) or record.rpc.function != function(op) or record.rpc.cpu_rm_gfid != 0) return error.Payload;
    if (record.rpc.result != 0) return error.FirmwareResult;
    const header: usize = switch (op) { .allocate => 32, .free => 16, else => 24 };
    const status_at: usize = if (op == .allocate) 16 else 12;
    const data = record.payload;
    if (data.len != header and data.len != request.len) return error.Payload;
    for (data[0..header], 0..) |value, i| {
        if (i >= status_at and i < status_at + 4) continue;
        if (value != request[i]) return error.Unexpected;
    }
    const status = word(data, status_at);
    if (status != 0) return .{ .rejected = status };
    if (data.len != request.len) return error.Payload;
    const payload = data[header..];
    switch (op) {
        .classes => if (word(payload, 0) > 100) return error.Bounds,
        .static_info => { _ = try staticInfo(payload); },
        .preserve, .instance => if (!std.mem.eql(u8, payload, request[header..])) return error.Payload,
        .allocate, .free => {},
    }
    return .{ .ok = payload };
}
pub fn supports(data: []const u8) bool {
    return supportsClass(data, root_class);
}
pub fn supportsClass(data: []const u8, class: u32) bool {
    if (data.len != 404 or word(data, 0) > 100) return false;
    for (0..word(data, 0)) |i| if (word(data, 4 + i * 4) == class) return true;
    return false;
}
pub fn staticInfo(data: []const u8) Error!StaticInfo {
    if (data.len != 36) return error.Payload;
    if (data[8] > 1 or data[28] > 1 or data[29] > 1 or word(data, 12) == 0 or word(data, 12) > 8 or
        word(data, 4) & ~@as(u32, 0xff) != 0 or word(data, 32) == 0 or word(data, 32) > 256) return error.Bounds;
    return .{ .capabilities = word(data, 0), .windows = word(data, 4), .fb_remapper = data[8] != 0,
        .heads = word(data, 12), .i2c_port = word(data, 16), .internal_displays = word(data, 20), .embedded_dp = word(data, 24),
        .external_mux = data[28] != 0, .internal_mux = data[29] != 0, .channels = word(data, 32) };
}
