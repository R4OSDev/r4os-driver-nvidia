//! RM-owned HPD/DP-IRQ event objects and bounded subscription lifecycle.
//! Caller retains the base RM graph and reserves all names before init; the
//! sole runtime token moves through this owner and any borrowed display query.
//! Freeing event objects is not device quiescence or permission to release DMA.
const std = @import("std");
const exchange = @import("gsp_exchange.zig");
const boot = @import("gsp_boot_events.zig");
const objects = @import("gsp_objects.zig");
const events = @import("gsp_runtime_events.zig");
const message = exchange.message;
pub const Error = exchange.Error;
pub const Kind = enum(u1) { hotplug, dp_irq };
pub const Handles = struct { hotplug: u32, dp_irq: u32 };
pub const Operation = union(enum) { allocate: Kind, enable: Kind, disable: Kind, free: Kind };
pub const callback_class: u32 = 0x7e;
pub const client_rm_flag: u32 = 0x04000000;
pub const notification_control: u32 = 0x20800301;
pub const max_request_bytes = 56;
pub fn index(kind: Kind) u32 {
    return if (kind == .hotplug) 1 else 7;
}
pub const Plan = struct {
    base: objects.Plan,
    handles: Handles,
    /// Names are reserved by the actual RM namespace owner, not synthesized
    /// from a connector index. Never reuse names while this run can emit them.
    pub fn init(base: objects.Plan, handles: Handles) Error!Plan {
        try base.validate();
        const names = [_]u32{ base.handles.client, base.handles.device, base.handles.subdevice, base.handles.display, handles.hotplug, handles.dp_irq };
        for (names, 0..) |name, i| {
            if (name == 0) return error.Handle;
            if (base.handles.i2c != 0 and name == base.handles.i2c) return error.Handle;
            for (names[0..i]) |previous| if (name == previous) return error.Handle;
        }
        return .{ .base = base, .handles = handles };
    }
    fn validate(self: *const Plan) Error!void {
        _ = try init(self.base, self.handles);
    }
    pub fn handle(self: *const Plan, kind: Kind) u32 {
        return if (kind == .hotplug) self.handles.hotplug else self.handles.dp_irq;
    }
};
pub const Initial = struct { notify_state: bool, info32: u32, info16: u16 };
pub const Response = union(enum) { ok: ?Initial, rm_error: u32, rpc_error: u32 };
pub const Encoded = struct { function: u32, bytes: []const u8 };
fn word(bytes: []const u8, offset: usize) u32 {
    return std.mem.readInt(u32, bytes[offset..][0..4], .little);
}
fn put(bytes: []u8, offset: usize, value: u32) void {
    std.mem.writeInt(u32, bytes[offset..][0..4], value, .little);
}
fn target(operation: Operation) Kind {
    return switch (operation) {
        inline else => |kind| kind,
    };
}
pub fn encode(plan: *const Plan, operation: Operation, output: []u8) Error!Encoded {
    try plan.validate();
    const kind = target(operation);
    const size: usize = switch (operation) {
        .allocate => 56,
        .enable, .disable => 44,
        .free => 16,
    };
    if (output.len < size) return error.Bounds;
    const bytes = output[0..size];
    @memset(bytes, 0);
    put(bytes, 0, plan.base.handles.client);
    switch (operation) {
        .allocate => {
            put(bytes, 4, plan.base.handles.subdevice);
            put(bytes, 8, plan.handle(kind));
            put(bytes, 12, callback_class);
            put(bytes, 20, 24); // Exact NV0005_ALLOC_PARAMETERS, pointer64 at16.
            put(bytes, 32, plan.base.handles.client);
            put(bytes, 40, callback_class);
            put(bytes, 44, client_rm_flag | index(kind));
            // hSrcResource=0 and data=NULL: no R4OS callback pointer on the wire.
            return .{ .function = 103, .bytes = bytes };
        },
        .enable, .disable => {
            put(bytes, 4, plan.base.handles.subdevice);
            put(bytes, 8, notification_control);
            put(bytes, 16, 20); // EVENT_SET_NOTIFICATION, including original padding.
            put(bytes, 24, index(kind));
            put(bytes, 28, if (operation == .enable) 2 else 0);
            return .{ .function = 76, .bytes = bytes };
        },
        .free => {
            put(bytes, 8, plan.handle(kind)); // NVOS00 parent remains null.
            return .{ .function = 10, .bytes = bytes };
        },
    }
}
pub fn decode(plan: *const Plan, operation: Operation, record: message.Record) Error!Response {
    const function: u32 = switch (operation) {
        .allocate => 103,
        .enable, .disable => 76,
        .free => 10,
    };
    if (record.rpc.function != function) return error.Unexpected;
    if (record.rpc.cpu_rm_gfid != 0) return error.Guest;
    if (record.rpc.result == message.pending) return error.Payload;
    if (record.rpc.result != 0) return .{ .rpc_error = record.rpc.result };
    const bytes = record.payload;
    const kind = target(operation);
    switch (operation) {
        .allocate => {
            if (bytes.len != 32 and bytes.len != 56) return error.Payload;
            if (word(bytes, 0) != plan.base.handles.client or word(bytes, 4) != plan.base.handles.subdevice or word(bytes, 8) != plan.handle(kind) or word(bytes, 12) != callback_class) return error.Unexpected;
            if (word(bytes, 20) != 24 or word(bytes, 24) != 0 or word(bytes, 28) != 0) return error.Payload;
            return if (word(bytes, 16) == 0) .{ .ok = null } else .{ .rm_error = word(bytes, 16) };
        },
        .enable, .disable => {
            if (bytes.len != 44) return error.Payload;
            if (word(bytes, 0) != plan.base.handles.client or word(bytes, 4) != plan.base.handles.subdevice or word(bytes, 8) != notification_control) return error.Unexpected;
            if (word(bytes, 16) != 20 or word(bytes, 20) != 0) return error.Payload;
            if (word(bytes, 12) != 0) return .{ .rm_error = word(bytes, 12) }; // No copyout-on-error.
            if (word(bytes, 24) != index(kind) or word(bytes, 28) != @as(u32, if (operation == .enable) 2 else 0)) return error.Unexpected;
            if (bytes[32] > 1) return error.Payload;
            return .{ .ok = .{ .notify_state = bytes[32] == 1, .info32 = word(bytes, 36), .info16 = std.mem.readInt(u16, bytes[40..42], .little) } };
        },
        .free => {
            if (bytes.len != 16) return error.Payload;
            if (word(bytes, 0) != plan.base.handles.client or word(bytes, 4) != 0 or word(bytes, 8) != plan.handle(kind)) return error.Unexpected;
            return if (word(bytes, 12) == 0) .{ .ok = null } else .{ .rm_error = word(bytes, 12) };
        },
    }
}
pub const Notification = enum { disabled, enabling, enabled, disabling, uncertain };
pub const Slot = struct { object: objects.Slot = .absent, notification: Notification = .disabled, initial: ?Initial = null };
pub const State = enum { creating, ready, loaned, rejected, destroying, objects_closed, finished, failed };
pub const Changes = struct { serial: u64 = 0, plug: u32 = 0, unplug: u32 = 0, dp_irq: u32 = 0, event_error: bool = false };
pub const Status = struct { operation: Operation, result: Response };
pub const Owner = struct {
    exchange: exchange.Exchange,
    plan: Plan,
    deadline: u64,
    state: State = .creating,
    slots: [2]Slot = @splat(.{}),
    request: [max_request_bytes]u8 = undefined,
    outstanding: ?Operation = null,
    last_status: ?Status = null,
    changes: Changes = .{},
    last_event_status: u32 = 0,
    last_event_data: u32 = 0,
    last_event_info16: u16 = 0,

    /// Parent graph must already be live and remain loaned until finish.
    /// Keep this value stable after the first poll or borrowed sink call.
    pub fn init(runtime: *boot.Handoff, plan: Plan, deadline: u64) Error!Owner {
        try plan.validate();
        if (plan.base.epoch != runtime.session.epoch) return error.Handle;
        return .{ .exchange = try exchange.Exchange.init(runtime, deadline), .plan = plan, .deadline = deadline };
    }
    fn fail(self: *Owner, reason: Error) Error {
        if (self.state == .loaned or self.state == .finished) return error.State;
        if (self.outstanding) |operation| {
            const slot = &self.slots[@intFromEnum(target(operation))];
            if (operation == .allocate or operation == .free) slot.object = .uncertain else slot.notification = .uncertain;
        }
        self.state = .failed;
        return self.exchange.fail(reason);
    }
    pub fn poll(self: *Owner) Error!?exchange.Dispatch {
        if (self.state != .creating and self.state != .destroying) return error.State;
        self.exchange.guard(self.deadline) catch |err| return self.fail(err);
        if (self.exchange.pending != null) return error.Pending;
        if (self.outstanding == null) {
            var operation: ?Operation = null;
            if (self.state == .creating) {
                for (self.slots, 0..) |slot, i| {
                    const kind: Kind = @enumFromInt(i);
                    if (slot.object == .absent) {
                        operation = .{ .allocate = kind };
                        break;
                    }
                    if (slot.object != .live) return self.fail(error.State);
                    if (slot.notification == .disabled) {
                        operation = .{ .enable = kind };
                        break;
                    }
                    if (slot.notification != .enabled) return self.fail(error.State);
                }
            } else {
                var i: usize = self.slots.len;
                while (i > 0) {
                    i -= 1;
                    const slot = self.slots[i];
                    const kind: Kind = @enumFromInt(i);
                    if (slot.object == .absent) continue;
                    if (slot.object != .live) return self.fail(error.State);
                    if (slot.notification == .enabled or slot.notification == .uncertain) {
                        operation = .{ .disable = kind };
                        break;
                    }
                    if (slot.notification != .disabled) return self.fail(error.State);
                    operation = .{ .free = kind };
                    break;
                }
            }
            if (operation) |value| {
                const bytes = try encode(&self.plan, value, &self.request);
                self.exchange.begin(bytes.function, bytes.bytes, self.deadline) catch |err| return self.fail(err);
                const slot = &self.slots[@intFromEnum(target(value))];
                switch (value) {
                    .allocate => slot.object = .creating,
                    .free => slot.object = .freeing,
                    .enable => slot.notification = .enabling,
                    .disable => slot.notification = .disabling,
                }
                self.outstanding = value;
            } else {
                self.state = if (self.state == .creating) .ready else .objects_closed;
                return null;
            }
        }
        const dispatch = (self.exchange.poll(self.deadline) catch |err| return self.fail(err)) orelse return null;
        if (!dispatch.response) return dispatch;
        const operation = self.outstanding.?;
        const response = decode(&self.plan, operation, dispatch.record) catch |err| return self.fail(err);
        self.last_status = .{ .operation = operation, .result = response };
        if (response == .rpc_error) return self.fail(error.FirmwareResult);
        self.exchange.complete(dispatch.ticket) catch |err| return self.fail(err);
        const slot = &self.slots[@intFromEnum(target(operation))];
        if (response == .rm_error) {
            if (operation == .allocate or operation == .enable) {
                if (operation == .allocate) slot.object = .absent else slot.notification = .uncertain;
                self.outstanding = null;
                self.state = .rejected; // Cleanup can disable a possibly enabled live event first.
                return null;
            }
            return self.fail(error.FirmwareResult); // Failed disable/free cannot release ancestors.
        }
        switch (operation) {
            .allocate => slot.object = .live,
            .enable => {
                slot.notification = .enabled;
                slot.initial = response.ok;
            },
            .disable => {
                slot.notification = .disabled;
                slot.initial = null;
            },
            .free => slot.* = .{},
        }
        self.outstanding = null;
        if (operation == .enable and target(operation) == .dp_irq) self.state = .ready;
        if (operation == .free and target(operation) == .hotplug) self.state = .objects_closed;
        return null;
    }
    pub fn loan(self: *Owner, deadline: u64) Error!objects.Loan {
        if (self.state != .ready or self.outstanding != null) return error.State;
        for (self.slots) |slot| if (slot.object != .live or slot.notification != .enabled) return error.State;
        const runtime = try self.exchange.handoff(deadline);
        self.state = .loaned;
        return .{ .runtime = runtime, .object = .{ .epoch = self.plan.base.epoch, .client = self.plan.base.handles.client, .display = self.plan.base.handles.display } };
    }
    pub fn reclaim(self: *Owner, runtime: *boot.Handoff, deadline: u64) Error!void {
        if (self.state != .loaned) return error.State;
        if (runtime.session != self.exchange.session or runtime.session.epoch != self.plan.base.epoch) return error.Handle;
        self.exchange = try exchange.Exchange.init(runtime, deadline);
        self.state = .ready;
    }
    pub fn beginDestroy(self: *Owner, deadline: u64) Error!void {
        if (self.state != .ready and self.state != .rejected) return error.State;
        if (self.outstanding != null or self.exchange.phase != .idle or self.exchange.pending != null) return error.State;
        self.exchange.guard(deadline) catch |err| return self.fail(err);
        self.deadline = deadline;
        self.state = .destroying;
    }
    pub fn finish(self: *Owner, deadline: u64) Error!boot.Handoff {
        if (self.state != .objects_closed or self.outstanding != null) return error.State;
        for (self.slots) |slot| if (slot.object != .absent) return error.State;
        const runtime = try self.exchange.handoff(deadline);
        self.state = .finished;
        return runtime;
    }
    fn from(p: *anyopaque) *Owner {
        return @ptrCast(@alignCast(p));
    }
    fn generation(p: *anyopaque) u64 {
        const self = from(p);
        if (self.state == .failed or self.state == .finished or self.state == .objects_closed or self.exchange.session.state != .active) return 0;
        return self.plan.base.epoch;
    }
    fn receipt(self: *Owner, scope: events.Scope) Error!void {
        if (generation(self) != scope.epoch or self.exchange.session.epoch != scope.epoch) return error.Stale;
        try self.exchange.session.guard(scope.deadline);
        const ticket = self.exchange.session.pending orelse return error.Stale;
        if (!std.meta.eql(ticket, scope.ticket)) return error.Stale;
    }
    fn resolve(self: *Owner, event: events.Event) Error!events.Display {
        if (event != .post_event) return error.Unexpected;
        const post = event.post_event;
        if (post.client != self.plan.base.handles.client) return error.Handle;
        for (self.slots, 0..) |slot, i| {
            const kind: Kind = @enumFromInt(i);
            if (post.event != self.plan.handle(kind)) continue;
            if (post.index != index(kind) or (slot.object != .live and slot.object != .freeing)) return error.Handle;
            // Exactly one registration per index on this subdevice, so the
            // addressed-event and notify-list forms resolve to the same sink.
            return (post.display() catch return error.Payload) orelse error.Unexpected;
        }
        return error.Handle;
    }
    fn admit(p: *anyopaque, scope: events.Scope, event: events.Event) error{ Denied, Unsupported }!void {
        const self = from(p);
        self.receipt(scope) catch return error.Denied;
        _ = self.resolve(event) catch return error.Denied;
        if (self.changes.serial == std.math.maxInt(u64)) return error.Denied;
    }
    fn deliver(p: *anyopaque, scope: events.Scope, event: events.Event) anyerror!void {
        const self = from(p);
        try self.receipt(scope);
        const value = try self.resolve(event);
        if (self.changes.serial == std.math.maxInt(u64)) return error.Exhausted;
        switch (value) {
            .hotplug => |v| {
                self.changes.plug |= v.plug_mask;
                self.changes.unplug |= v.unplug_mask;
            },
            .dp_irq => |v| self.changes.dp_irq |= v,
        }
        const post = event.post_event;
        self.changes.event_error = self.changes.event_error or post.status != 0;
        self.last_event_status = post.status;
        self.last_event_data = post.data;
        self.last_event_info16 = post.info16;
        self.changes.serial += 1;
        try self.receipt(scope);
    }
    pub fn sink(self: *Owner) events.Sink {
        return .{ .context = self, .generation = generation, .admit = admit, .deliver = deliver };
    }
    /// Coalesced change masks only. Consumers must refresh monitor/EDID/link
    /// state; initial notification outputs and these masks are not live state.
    pub fn takeChanges(self: *Owner, deadline: u64) Error!Changes {
        if (self.state != .ready and self.state != .loaned) return error.State;
        try self.exchange.session.guard(deadline);
        if (self.exchange.session.pending != null) return error.Pending;
        const result = self.changes;
        self.changes = .{ .serial = result.serial };
        return result;
    }
};
