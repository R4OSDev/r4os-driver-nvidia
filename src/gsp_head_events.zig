//! Head LAST_DATA observations from the real GSP display interrupt vector.
//! IRQ owns the bounded writes; workers read copied metadata without MMIO.
//! Sequence counts observed hardware events, not estimated refresh periods.
const std = @import("std");
pub const max_heads = 8;
pub const reg = struct {
    pub const dispatch: u32 = 0x611ec0;
    pub const status: u32 = 0x611c00;
    pub const clear: u32 = 0x611800;
    pub const enable: u32 = 0x611d80;
    pub const position: u32 = 0x616330;
    pub const last_data: u32 = 2;
};
pub const Sample = struct {
    sequence: u64 = 0,
    observed_ns: u64 = 0,
    frame_counter: u16 = 0,
    scanline: u16 = 0,
};
pub const Head = struct {
    revision: u64 = 0,
    sequence: u64 = 0,
    observed_ns: u64 = 0,
    position: u32 = 0,

    // Single serialized IRQ writer. A seqlock preserves the association of
    // sequence/time/position without a task lock or unbounded reader retry.
    fn observe(self: *Head, now: u64, position: u32) !void {
        const prior = @atomicLoad(u64, &self.observed_ns, .monotonic);
        if (now == 0 or now == std.math.maxInt(u64) or now < prior) return error.Clock;
        const revision = @atomicLoad(u64, &self.revision, .monotonic);
        const sequence = @atomicLoad(u64, &self.sequence, .monotonic);
        if (revision > std.math.maxInt(u64) - 2 or sequence == std.math.maxInt(u64)) return error.Sequence;
        _ = @atomicRmw(u64, &self.revision, .Add, 1, .acq_rel);
        @atomicStore(u64, &self.sequence, sequence + 1, .monotonic);
        @atomicStore(u64, &self.observed_ns, now, .monotonic);
        @atomicStore(u32, &self.position, position, .monotonic);
        @atomicStore(u64, &self.revision, revision + 2, .release);
    }
    pub fn snapshot(self: *const Head) ?Sample {
        for (0..3) |_| {
            const before = @atomicLoad(u64, &self.revision, .seq_cst);
            if (before & 1 != 0) continue;
            const sequence = @atomicLoad(u64, &self.sequence, .seq_cst);
            const time = @atomicLoad(u64, &self.observed_ns, .seq_cst);
            const position = @atomicLoad(u32, &self.position, .seq_cst);
            const after = @atomicLoad(u64, &self.revision, .seq_cst);
            if (before == after) return .{ .sequence = sequence, .observed_ns = time,
                .frame_counter = @truncate(position >> 16), .scanline = @truncate(position) };
        }
        return null;
    }
};
pub const Owner = struct {
    epoch: u64 = 0,
    head_mask: u32 = 0,
    leaf: u32 = 0,
    bit: u32 = 0,
    subtree: u32 = 0,
    enabled: bool = false,
    heads: [max_heads]Head = @splat(.{}),

    /// The outer IRQ gate is exclusively held, delivery unarmed. GSP owns
    /// display setup; touch only our admitted heads' LAST_DATA enable bit.
    pub fn enable(self: *Owner, io: anytype, epoch: u64, vector: u32, mask: u32) !void {
        if (self.epoch != 0 or epoch == 0 or vector >= 256 or mask == 0 or mask & ~@as(u32, 0xff) != 0) return error.Binding;
        self.epoch = epoch; self.head_mask = mask;
        self.leaf = vector / 32; self.bit = @as(u32, 1) << @as(u5, @intCast(vector % 32));
        self.subtree = @as(u32, 1) << @as(u5, @intCast(vector / 64));
        // Mark before the first effect so partial setup still disables the
        // same sources on shutdown. It does not imply a received event.
        self.enabled = true;
        for (0..max_heads) |head| if (mask & (@as(u32, 1) << @intCast(head)) != 0) {
            const offset: u32 = @intCast(head * 4);
            io.write(reg.clear + offset, reg.last_data);
            io.write(reg.enable + offset, io.read(reg.enable + offset) | reg.last_data);
        };
    }
    pub fn disable(self: *Owner, io: anytype) void {
        if (!self.enabled) return;
        for (0..max_heads) |head| if (self.head_mask & (@as(u32, 1) << @intCast(head)) != 0) {
            const offset: u32 = @intCast(head * 4);
            io.write(reg.enable + offset, io.read(reg.enable + offset) & ~reg.last_data);
        };
        self.enabled = false;
    }
    /// Called only for this display leaf. Do not acknowledge other heads or
    /// supervisor/awaken causes. Those require their own implemented owner.
    pub fn interrupt(self: *Owner, io: anytype, now: u64) !u32 {
        if (!self.enabled) return error.State;
        const dispatch = io.read(reg.dispatch);
        if (dispatch & ~self.head_mask != 0) return error.DisplayInterrupt;
        var seen: u32 = 0;
        for (0..max_heads) |head| {
            const bit = @as(u32, 1) << @as(u5, @intCast(head));
            if (dispatch & bit == 0) continue;
            const offset: u32 = @intCast(head * 4);
            const status = io.read(reg.status + offset);
            if (status & ~reg.last_data != 0) return error.DisplayInterrupt;
            if (status & reg.last_data == 0) continue;
            const position = io.read(reg.position + @as(u32, @intCast(head)) * 0x800);
            try self.heads[head].observe(now, position);
            io.write(reg.clear + offset, reg.last_data);
            seen |= bit;
        }
        return seen;
    }
};
