//! GA106 GSP interrupt endpoint. Register/close run in serialized DriverWork.
//! IRQs use an immutable borrowed MMIO view, atomics, a cached monotonic
//! clock and one semaphore release. No task-owned lease validation,
//! queue/DMA access, table lookup or logging in IRQ.
const std = @import("std");
const r4os = @import("r4os");
const a = r4os.abi;
const bar0 = @import("bar0.zig");
const identity = @import("identity.zig");
const postinit = @import("gsp_postinit.zig");
pub const reg = struct {
    pub const leaf: u32 = 0xb81000;
    pub const allow: u32 = 0xb81200;
    pub const block: u32 = 0xb81400;
    pub const top: u32 = 0xb81600;
    pub const rearm: u32 = 0xb81608;
    pub const unarm: u32 = 0xb81610;
    pub const msi: u32 = 0x088704;
    pub const clear: u32 = 0x110004;
    pub const status: u32 = 0x110008;
    pub const mask_clear: u32 = 0x110014;
    pub const retrigger: u32 = 0x1103e8;
    pub const mask: u32 = 0x111528;
    pub const bytes: u32 = 0xb82000;
};
pub const Wake = struct { context: usize, signal: *const fn (usize) i32 };
pub const Owner = struct {
    self_address: usize = 0,
    ctx: ?r4os.r4dev.DriverContext = null,
    lease: bar0.Lease = .{},
    cpu: u64 = 0,
    boot0: u32 = 0,
    pci: a.PciDeviceInfo = .{},
    wake: ?Wake = null,
    irq: u8 = 0,
    msi: bool = false,
    registered: bool = false,
    routing_uncertain: bool = false,
    touched: bool = false,
    closed: bool = false,
    leaf: u32 = 0,
    bit: u32 = 0,
    subtree: u32 = 0,
    // 0: disabled, 1: admitted, 2: handler active, 3: handler must retire.
    // close never touches hardware while state 2/3 owns the MMIO sequence.
    gate: u32 = 0,
    fault: u32 = 0,
    last_raw: u32 = 0,
    last_mask: u32 = 0,
    interrupts: u64 = 0,
    messages: u64 = 0,
    last_status: i32 = 0,
    clock: ?r4os.r4dev.DriverResourceContext = null,
    display: @import("gsp_head_events.zig").Owner = .{},

    pub fn open(self: *Owner, ctx: *const r4os.r4dev.DriverContext, mapping: *bar0.Owner,
        snapshot: *const identity.Snapshot, chip: identity.Chip, inventory: *const postinit.Data,
        wake: Wake, boot0: u32) !void
    {
        if (self.self_address != 0) return error.State;
        const index = inventory.gsp_index orelse return error.Vector;
        if (index >= inventory.entry_count or index >= inventory.entries.len or
            inventory.entries[index].engine != postinit.gsp_engine) return error.Vector;
        const vector = inventory.entries[index].stall;
        if (chip.id != 0x176 or vector >= postinit.vector_count or snapshot.bars[0].bytes < reg.bytes) return error.Profile;
        self.self_address = @intFromPtr(self);
        self.ctx = ctx.*;
        self.wake = wake;
        self.boot0 = boot0;
        self.leaf = vector / 32;
        self.bit = @as(u32, 1) << @as(u5, @intCast(vector % 32));
        self.subtree = @as(u32, 1) << @as(u5, @intCast(vector / 64));
        self.pci = .{ .bus_kind = snapshot.pci.bus_kind, .bus = snapshot.pci.bus,
            .device = snapshot.pci.device, .function = snapshot.pci.function };
        try self.lease.acquire(mapping, ctx, snapshot, chip);
        self.cpu = (try self.lease.view(0, reg.bytes)).cpu_address;
        if (self.read(0) != boot0) return error.IdentityChanged;
        // GSP firmware already owns this held GPU. Block every unowned leaf;
        // only the returned GSP vector will be allowed in this endpoint.
        self.touched = true;
        self.write(reg.unarm, 15);
        for (0..8) |leaf| self.write(reg.block + @as(u32, @intCast(leaf)) * 4, 0xffffffff);
        if (!self.flush()) return error.IdentityChanged;
        if (snapshot.caps.msi != 0) {
            self.last_status = ctx.pciEnableMsi(self.pci);
            if (self.last_status >= 0 and self.last_status < 32) {
                self.irq = @intCast(self.last_status);
                self.msi = true;
            } else if (self.last_status != -1 and self.last_status != -2 and self.last_status != -3) {
                self.routing_uncertain = true;
                return error.Msi;
            }
        }
        if (!self.msi) {
            if (snapshot.command & (1 << 10) != 0 or snapshot.interrupt_line >= 24 or
                snapshot.interrupt_pin == 0 or snapshot.interrupt_pin > 4) return error.Route;
            self.irq = snapshot.interrupt_line;
        }
        self.last_status = ctx.irqRegister(self.irq, interrupt, self.self_address,
            if (self.msi) a.irq_flag_msi else a.irq_flag_shared | a.irq_flag_level_low);
        if (self.last_status != 0) return error.Irq;
        self.registered = true;
        self.write(reg.leaf + self.leaf * 4, self.bit);
        self.write(reg.allow + self.leaf * 4, self.bit);
        self.write(reg.clear, 0x40);
        if (self.msi) self.write(reg.msi, 0);
        if (!self.flush()) return error.IdentityChanged;
        // Publish immutable fields before delivery. A handler cannot observe
        // a partially installed owner; all cleanup paths retain this address.
        @atomicStore(u32, &self.gate, 1, .release);
        self.write(reg.rearm, self.subtree);
        if (!self.flush()) { self.latch(1); return error.IdentityChanged; }
    }

    pub fn read(self: *const Owner, offset: u32) u32 {
        const word: *volatile u32 = @ptrFromInt(self.cpu + offset);
        return word.*;
    }
    pub fn write(self: *const Owner, offset: u32, value: u32) void {
        const word: *volatile u32 = @ptrFromInt(self.cpu + offset);
        word.* = value;
    }
    fn flush(self: *const Owner) bool {
        asm volatile ("mfence" ::: .{ .memory = true });
        return self.read(0) == self.boot0;
    }
    fn latch(self: *Owner, fault: u32) void {
        _ = @cmpxchgStrong(u32, &self.fault, 0, fault, .release, .monotonic);
    }
    pub fn failed(self: *const Owner) bool { return @atomicLoad(u32, &self.fault, .acquire) != 0; }

    pub fn enableDisplay(self: *Owner, inventory: *const postinit.Data, epoch: u64, head_mask: u32) !void {
        if (self.self_address != @intFromPtr(self) or !self.registered or self.closed or self.failed() or self.display.epoch != 0) return error.State;
        const index = inventory.display_index orelse return error.Vector;
        if (index >= inventory.entry_count or index >= inventory.entries.len or inventory.entries[index].engine != postinit.display_engine) return error.Vector;
        const vector = inventory.entries[index].stall;
        if (vector >= postinit.vector_count or vector == self.leaf * 32 + @ctz(self.bit)) return error.Vector;
        const clock = self.ctx.?.resources() orelse return error.Api;
        if (clock.nowNs() == std.math.maxInt(u64)) return error.Clock;
        if (@cmpxchgStrong(u32, &self.gate, 1, 2, .acq_rel, .acquire) != null) return error.Busy;
        defer self.leave();
        self.write(reg.unarm, 15);
        if (!self.flush()) { self.latch(1); return error.IdentityChanged; }
        self.clock = clock;
        try self.display.enable(self, epoch, vector, head_mask);
        self.write(reg.leaf + self.display.leaf * 4, self.display.bit);
        self.write(reg.allow + self.display.leaf * 4, self.display.bit);
        if (!self.flush()) { self.latch(1); return error.IdentityChanged; }
    }

    fn leave(self: *Owner) void {
        // close can request retirement while an IRQ or setup owns the gate.
        if (!self.failed() and @atomicLoad(u32, &self.gate, .acquire) == 2) {
            self.write(reg.rearm, self.subtree | if (self.display.enabled) self.display.subtree else @as(u32, 0));
            if (!self.flush()) self.latch(1);
        }
        if (self.failed()) @atomicStore(u32, &self.gate, 0, .release) else
            if (@cmpxchgStrong(u32, &self.gate, 2, 1, .release, .monotonic) != null)
                @atomicStore(u32, &self.gate, 0, .release);
    }

    fn interrupt(irq: u8, raw: usize) callconv(.c) u32 {
        const self: *Owner = @ptrFromInt(raw);
        if (self.self_address != raw or irq != self.irq or
            @cmpxchgStrong(u32, &self.gate, 1, 2, .acq_rel, .acquire) != null) return 0;
        defer self.leave();
        self.write(reg.unarm, 15);
        if (self.msi) self.write(reg.msi, 0);
        if (!self.flush()) {
            self.latch(1);
            self.signal();
            return a.irq_result_handled;
        }
        const top = self.read(reg.top);
        const gsp_pending = top & self.subtree != 0 and self.read(reg.leaf + self.leaf * 4) & self.bit != 0;
        const display_pending = self.display.enabled and top & self.display.subtree != 0 and self.read(reg.leaf + self.display.leaf * 4) & self.display.bit != 0;
        if (!gsp_pending and !display_pending) return 0;
        _ = @atomicRmw(u64, &self.interrupts, .Add, 1, .monotonic);
        if (display_pending) {
            self.write(reg.leaf + self.display.leaf * 4, self.display.bit);
            _ = self.display.interrupt(self, self.clock.?.nowNs()) catch blk: { self.latch(4); break :blk 0; };
        }
        if (!gsp_pending) {
            if (!self.flush()) self.latch(1);
            self.signal();
            return a.irq_result_handled;
        }
        self.write(reg.leaf + self.leaf * 4, self.bit);
        const status = self.read(reg.status);
        const mask = self.read(reg.mask);
        @atomicStore(u32, &self.last_raw, status, .monotonic);
        @atomicStore(u32, &self.last_mask, mask, .monotonic);
        const pending = status & mask;
        if (pending & 0x40 != 0) {
            self.write(reg.clear, 0x40);
            _ = @atomicRmw(u64, &self.messages, .Add, 1, .monotonic);
        }
        const unexpected = pending & ~@as(u32, 0x40);
        if (unexpected != 0) {
            self.write(reg.mask_clear, unexpected);
            self.write(reg.clear, unexpected);
        }
        if (pending == 0 or unexpected != 0) self.latch(2);
        if (pending != 0) self.write(reg.retrigger, 1);
        if (!self.flush()) self.latch(1);
        self.signal();
        return a.irq_result_handled;
    }
    fn signal(self: *Owner) void {
        const wake = self.wake.?;
        if (wake.signal(wake.context) != 0) self.latch(3);
    }

    /// Nonblocking retirement. Busy/failure retains the callback, MSI and
    /// mapping. The serialized owner retries before resetting firmware.
    pub fn close(self: *Owner) bool {
        if (self.self_address == 0 or self.closed) return true;
        if (self.self_address != @intFromPtr(self)) return false;
        var retired = false;
        for (0..4) |_| {
            const gate = @atomicLoad(u32, &self.gate, .acquire);
            if (gate == 0) { retired = true; break; }
            if (gate == 3) return false;
            if (@cmpxchgStrong(u32, &self.gate, gate, if (gate == 2) 3 else 0, .acq_rel, .acquire) == null) {
                if (gate == 2) return false;
                retired = true;
                break;
            }
        }
        if (!retired) return false;
        if (self.touched) {
            self.write(reg.unarm, 15);
            if (self.display.epoch != 0) {
                self.write(reg.block + self.display.leaf * 4, self.display.bit);
                if (self.flush()) self.display.disable(self);
            }
            self.write(reg.block + self.leaf * 4, self.bit);
            // A removed GPU need not answer, but its CPU callback must still
            // retire. The display/DMA graph is retained by the outer owner.
            _ = self.flush();
        }
        if (self.registered) {
            self.last_status = self.ctx.?.irqUnregister(self.irq, interrupt, self.self_address);
            if (self.last_status != 0) return false;
            self.registered = false;
        }
        if (self.routing_uncertain) return false;
        if (self.msi) {
            self.last_status = self.ctx.?.pciDisableMsi(self.pci);
            if (self.last_status != 0) return false;
            self.msi = false;
        }
        if (!self.lease.release()) return false;
        self.closed = true;
        return true;
    }
};
